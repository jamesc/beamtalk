//! The runtime sentinel atoms that cross the Rust/Erlang boundary (BT-4901).
//!
//! **DDD Context:** Compilation — Code Generation
//!
//! Generated Core Erlang and the Erlang runtime must agree on a handful of
//! reserved atoms: the non-local-return tuple tag, the `handle_continue`
//! queue tag, the actor init-ack key, the call-stack process-dictionary key
//! and the distribution-wire envelope tag. This module is the one Rust source;
//! [`erlang_header`] renders it into the checked-in
//! `runtime/apps/beamtalk_runtime/include/beamtalk_sentinel_tags.hrl`
//! (regenerated by `beamtalk build-stdlib`, guarded by
//! `just check-generated-builtins`), which `beamtalk.hrl` includes. Codegen
//! reads the constants below; the runtime reads the macros.

/// First element of a `^` non-local-return throw tuple (ADR 0041).
pub const NLR: &str = "$bt_nlr";
/// Tag of the `handle_continue/2` term carrying an actor's continuation queue.
pub const CONTINUE: &str = "$bt_continue";
/// State-map / process-dictionary key carrying an actor's init-ack target.
pub const INIT_ACK: &str = "$bt_init_ack";
/// Process-dictionary key holding the actor's current call stack.
pub const CALL_STACK: &str = "$bt_call_stack";
/// First element of the versioned distribution-wire request envelope
/// (ADR 0126 §5.1).
pub const WIRE: &str = "$beamtalk_wire";

// The three constants below (`CLASS_TAG`, `CLASS_MOD`, `SKIP_INITIALIZE`) are
// exported as macros, but the runtime does not read them yet: its `.erl` files
// still spell these atoms by hand (BT-5041 follow-up). Codegen reads them.

/// Key of the class tag in every value-type map and actor state map
/// (`'$beamtalk_class' => 'Counter'`).
pub const CLASS_TAG: &str = "$beamtalk_class";
/// Actor state-map key carrying the instance's compiled class module.
pub const CLASS_MOD: &str = "__class_mod__";
/// `init/1` argument key a child sets when it calls its parent's `init/1` as a
/// state-building helper (so the parent skips `initialize`).
pub const SKIP_INITIALIZE: &str = "__skip_initialize__";

/// Content of `beamtalk_sentinel_tags.hrl`, generated from the constants above.
#[must_use]
pub fn erlang_header() -> String {
    format!(
        "%% AUTO-GENERATED by `beamtalk build-stdlib` from \
         crates/beamtalk-codegen/src/core_erlang/sentinel_tags.rs — do not edit manually.\n\
         %% Copyright 2026 James Casey\n\
         %% SPDX-License-Identifier: Apache-2.0\n\
         \n\
         %% The reserved atoms generated Core Erlang and the runtime must agree on.\n\
         %% Regenerate with `just build-stdlib`; `just check-generated-builtins` fails\n\
         %% when this file is stale.\n\
         \n\
         -ifndef(BEAMTALK_SENTINEL_TAGS_HRL).\n\
         -define(BEAMTALK_SENTINEL_TAGS_HRL, true).\n\
         \n\
         %% First element of a `^` non-local-return throw tuple (ADR 0041).\n\
         -define(BT_NLR_TAG, '{NLR}').\n\
         \n\
         %% Tag of the `handle_continue/2` term carrying an actor's continuation queue.\n\
         -define(BT_CONTINUE_TAG, '{CONTINUE}').\n\
         \n\
         %% Key carrying an actor's init-ack target during `init/1`.\n\
         -define(BT_INIT_ACK_KEY, '{INIT_ACK}').\n\
         \n\
         %% Process-dictionary key holding the actor's current call stack.\n\
         -define(BT_CALL_STACK_KEY, '{CALL_STACK}').\n\
         \n\
         %% First element of the versioned distribution-wire request envelope.\n\
         -define(BT_WIRE_TAG, '{WIRE}').\n\
         \n\
         %% Class tag key of every value-type map and actor state map.\n\
         -define(BT_CLASS_TAG_KEY, '{CLASS_TAG}').\n\
         \n\
         %% Actor state-map key carrying the instance's compiled class module.\n\
         -define(BT_CLASS_MOD_KEY, '{CLASS_MOD}').\n\
         \n\
         %% `init/1` argument key a child sets when calling its parent's `init/1`\n\
         %% as a state-building helper.\n\
         -define(BT_SKIP_INITIALIZE_KEY, '{SKIP_INITIALIZE}').\n\
         \n\
         -endif.\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn header_defines_every_sentinel() {
        let h = erlang_header();
        for (macro_name, atom) in [
            ("BT_NLR_TAG", NLR),
            ("BT_CONTINUE_TAG", CONTINUE),
            ("BT_INIT_ACK_KEY", INIT_ACK),
            ("BT_CALL_STACK_KEY", CALL_STACK),
            ("BT_WIRE_TAG", WIRE),
            ("BT_CLASS_TAG_KEY", CLASS_TAG),
            ("BT_CLASS_MOD_KEY", CLASS_MOD),
            ("BT_SKIP_INITIALIZE_KEY", SKIP_INITIALIZE),
        ] {
            assert!(
                h.contains(&format!("-define({macro_name}, '{atom}').")),
                "{macro_name} missing: {h}"
            );
        }
    }
}
