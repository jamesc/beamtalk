/// Remove a single file, ignoring `NotFound` but propagating other errors.
///
/// Used by stale-file cleanup to avoid TOCTOU races (`exists()` + `remove_file()`
/// is racy if another process creates/removes the file between the two calls).
pub(super) fn remove_file_if_exists(path: &std::path::Path) -> Result<()> {
    if let Err(err) = fs::remove_file(path)
        && err.kind() != std::io::ErrorKind::NotFound
    {
        return Err(miette!(
            "Failed to remove stale file {}: {err}",
            path.display()
        ));
    }
    Ok(())
}

/// Remove stale runtime files (`node.info`, `port`, `pid`, `starting`) from a workspace directory.
///
/// These files are written during workspace startup and must be cleaned before
/// restarting a node — a stale `port` file can cause `start_detached_node` to
/// connect to the wrong BEAM node, and a stale `pid` file can report the wrong
/// process.  The `starting` tombstone is written at the very beginning of
/// `start_detached_node` and removed on success; its presence here indicates a
/// partial startup that was interrupted.
///
/// **`startup.log` is intentionally preserved**: the retry helpers
/// and panic messages in `start_detached_node` reference this file by path as
/// the user-facing diagnostic ("Check …/startup.log"). Deleting it between
/// attempts (or after the final failure) would strip the referenced error
/// content. `start_detached_node` clears `startup.log` itself immediately
/// before spawning a fresh BEAM node so no stale content leaks into a new run.
///
/// Called by:
/// - `cleanup_stale_node_info` — after detecting an orphaned workspace
/// - `start_detached_node` (via `process.rs`) — before spawning a new BEAM node
pub fn remove_stale_runtime_files(workspace_id: &str) -> Result<()> {
    let ws_dir = workspace_dir(workspace_id)?;
    remove_file_if_exists(&ws_dir.join("node.info"))?;
    remove_file_if_exists(&ws_dir.join("port"))?;
    // Atomic port file write (beamtalk_repl_server) writes to port.tmp then
    // renames to port.  A crash between those two steps leaves a stale tmp file.
    remove_file_if_exists(&ws_dir.join("port.tmp"))?;
    remove_file_if_exists(&ws_dir.join("pid"))?;
    remove_file_if_exists(&ws_dir.join("starting"))?;
    // NOTE: `startup.log` is deliberately NOT removed here.
    // The file is cleared by `start_detached_node` immediately before spawning
    // a fresh BEAM node, and otherwise kept so retry/panic messages pointing
    // at its path remain valid.
    Ok(())
}

/// Clean up stale runtime files for a workspace.
///
/// Removes `node.info`, `port`, `pid`, and `starting` files. Use when an orphaned
/// workspace is detected (stale `node.info` but node not running) or after graceful
/// shutdown. Delegates to [`remove_stale_runtime_files`].
pub fn cleanup_stale_node_info(workspace_id: &str) -> Result<()> {
    remove_stale_runtime_files(workspace_id)
}

/// Acquire an exclusive advisory lock for workspace creation.
///
/// Returns a locked `File` handle. The lock is released when the file is dropped.
/// The lockfile is created at [`workspace_lockfile_path`].
pub(super) fn acquire_workspace_lock(workspace_id: &str) -> Result<fs::File> {
    let lockfile_path = workspace_lockfile_path(workspace_id)?;
    fs::create_dir_all(workspaces_base_dir()?).into_diagnostic()?;

    // Shared with the directory locks: logs a "waiting" message when another
    // process holds the lock (workspace startup can hold it for minutes).
    crate::commands::dir_lock::lock_file(&lockfile_path, "workspace")
}

