//! Lockfile management for reproducible builds (ADR 0070 Phase 1, ADR 0072 Phase 2).
//!
//! **DDD Context:** Build System
//!
//! The lockfile (`beamtalk.lock`) pins exact commit SHAs for git dependencies
//! and exact versions + checksums for native (hex.pm) dependencies, or the
//! resolved commit SHA for native git dependencies.
//! Path dependencies are intentionally NOT locked — they resolve to whatever
//! is on disk, so they are only reproducible within a single checkout.
//!
//! ## Format
//!
//! The lockfile uses a simple, human-readable, git-friendly format:
//!
//! ```text
//! # This file is auto-generated by beamtalk. Do not edit manually.
//! # It pins exact versions of dependencies for reproducible builds.
//!
//! [[package]]
//! name = "json"
//! url = "https://github.com/jamesc/beamtalk-json"
//! reference = "tag:v1.0.0"
//! sha = "abc1234def5678..."
//!
//! # A registry dependency additionally records the exact version requested
//! # in beamtalk.toml, plus which registry produced it, so resolution can
//! # skip the registry index on a hit — and re-consult it when the
//! # configured registry changes.
//! [[package]]
//! name = "yaml"
//! version = "0.2.1"
//! registry = "https://github.com/jamesc/beamtalk-registry"
//! url = "https://github.com/jamesc/beamtalk-yaml"
//! reference = "tag:v0.2.1"
//! sha = "fed4321cba9876..."
//!
//! [[native_package]]
//! name = "gun"
//! version = "2.1.3"
//! sha = "def456..."
//!
//! [[native_package]]
//! name = "cowboy"
//! version = "2.12.0"
//! sha = "ghi789..."
//!
//! # A native git dependency records its URL, the reference it was resolved
//! # from (absent for transitive git deps) and the resolved commit SHA.
//! [[native_package]]
//! name = "oidcc"
//! git = "https://github.com/jamesc/oidcc"
//! reference = "branch:rfc7009-revocation"
//! sha = "0123abcd..."
//! ```

use beamtalk_core::compilation::GitReference;
use camino::Utf8Path;
use miette::{Context, IntoDiagnostic, Result};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::commands::toml_utils::escape_toml_string;

/// The lockfile filename.
#[allow(dead_code)] // Used by tests; will be called by build system (ADR 0070 Phase 2+)
pub const LOCKFILE_NAME: &str = "beamtalk.lock";

/// The lockfile header comment.
const LOCKFILE_HEADER: &str = "\
# This file is auto-generated by beamtalk. Do not edit manually.
# It pins exact versions of dependencies for reproducible builds.
";

/// A single locked git dependency entry.
#[derive(Debug, Clone, PartialEq, Eq)]
#[allow(dead_code)] // Used by tests; will be called by build system (ADR 0070 Phase 2+)
pub struct LockEntry {
    /// The dependency name.
    pub name: String,
    /// The git repository URL.
    pub url: String,
    /// The requested reference (tag/branch/rev from `beamtalk.toml`).
    pub reference: GitReference,
    /// The exact commit SHA this reference resolved to.
    pub resolved_sha: String,
    /// For a registry dependency, the exact version requested in
    /// `beamtalk.toml` plus which registry produced this entry.
    ///
    /// `None` for plain git dependencies. A lock entry whose recorded version
    /// *and* registry both still match lets resolution skip the registry
    /// index entirely and go straight to the git checkout.
    pub registry_version: Option<RegistryVersion>,
}

/// Registry provenance recorded on a [`LockEntry`] for a dependency resolved
/// through a registry index.
///
/// Serialized as two separate lockfile fields: `version` and `registry` (the
/// latter's name matches the field ADR 0073 reserves for this purpose).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RegistryVersion {
    /// The exact version requested in `beamtalk.toml` when this entry was
    /// resolved.
    pub version: String,
    /// Where the registry index that produced this entry was resolved from
    /// (its location string — a git URL or local directory path).
    ///
    /// `None` for a lock entry written before this field existed —
    /// such an entry never matches the currently configured registry, so it
    /// is always treated as a miss and re-resolved once, after which it
    /// carries a real value.
    pub registry: Option<String>,
}

/// A locked native dependency entry (ADR 0072 Phase 2).
///
/// Stores the exact resolved version and checksums for a hex package, or the
/// resolved commit SHA for a git dependency — including transitive
/// dependencies resolved by rebar3.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NativePackageLock {
    /// The OTP application name (e.g., "gun", "cowboy", "ranch").
    pub name: String,
    /// rebar3's dependency level: 0 for a direct dependency of the build,
    /// 1+ for transitive ones. `None` for an entry written before levels
    /// were recorded.
    pub level: Option<u32>,
    /// Where the locked package came from.
    pub source: NativeLockSource,
}

/// The resolved source of a locked native dependency.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NativeLockSource {
    /// A hex.pm package at an exact version.
    Hex {
        /// The hex package name — differs from the application name only
        /// for an aliased dependency.
        package: String,
        /// The exact resolved version (e.g., "2.1.3").
        version: String,
        /// The hex inner checksum (`pkg_hash`).
        checksum: String,
        /// The hex outer checksum (`pkg_hash_ext`), when rebar3 recorded one.
        outer_checksum: Option<String>,
    },
    /// A git repository at an exact commit.
    Git {
        /// The repository URL.
        url: String,
        /// The manifest reference the commit was resolved from, so a later
        /// build can tell whether the lock is still current. `None` for a
        /// transitive git dependency no `beamtalk.toml` declares.
        reference: Option<GitReference>,
        /// The resolved commit SHA.
        sha: String,
    },
}

impl NativePackageLock {
    /// The same entry at rebar3 dependency level `level`.
    #[must_use]
    pub fn at_level(mut self, level: u32) -> Self {
        self.level = Some(level);
        self
    }
}

#[cfg(test)]
impl NativePackageLock {
    /// A locked hex package named after its application, with no level or
    /// outer checksum.
    pub fn hex(name: &str, version: &str, checksum: &str) -> Self {
        Self {
            name: name.to_string(),
            level: None,
            source: NativeLockSource::Hex {
                package: name.to_string(),
                version: version.to_string(),
                checksum: checksum.to_string(),
                outer_checksum: None,
            },
        }
    }

    /// A locked git dependency, with no level or recorded manifest reference.
    pub fn git(name: &str, url: &str, sha: &str) -> Self {
        Self {
            name: name.to_string(),
            level: None,
            source: NativeLockSource::Git {
                url: url.to_string(),
                reference: None,
                sha: sha.to_string(),
            },
        }
    }

    /// The locked hex version, or `None` for a git entry.
    pub fn hex_version(&self) -> Option<&str> {
        match &self.source {
            NativeLockSource::Hex { version, .. } => Some(version),
            NativeLockSource::Git { .. } => None,
        }
    }

    /// The locked hex checksum, or `None` for a git entry.
    pub fn hex_checksum(&self) -> Option<&str> {
        match &self.source {
            NativeLockSource::Hex { checksum, .. } => Some(checksum),
            NativeLockSource::Git { .. } => None,
        }
    }
}

/// The full lockfile contents — an ordered collection of lock entries.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Lockfile {
    /// Locked git packages, keyed by dependency name.
    pub packages: BTreeMap<String, LockEntry>,
    /// Locked native (hex) packages, keyed by package name (ADR 0072 Phase 2).
    pub native_packages: BTreeMap<String, NativePackageLock>,
}

/// Intermediate TOML representation for serialization.
#[derive(Debug, Serialize, Deserialize)]
#[allow(dead_code)] // Constructed by serde deserialization
struct TomlLockfile {
    #[serde(default)]
    package: Vec<TomlLockEntry>,
    #[serde(default)]
    native_package: Vec<TomlNativePackageEntry>,
}

/// A single git package entry in the TOML lockfile.
#[derive(Debug, Serialize, Deserialize)]
#[allow(dead_code)] // Constructed by serde deserialization
struct TomlLockEntry {
    name: String,
    /// The registry version, when this package was resolved from the registry.
    /// Absent in lockfiles written before registry support — old lockfiles
    /// therefore still parse, and their entries simply carry no version.
    #[serde(default)]
    version: Option<String>,
    /// Which registry produced this entry. Absent in lockfiles
    /// written before this field existed, and in plain git-dependency
    /// entries — both still parse.
    #[serde(default)]
    registry: Option<String>,
    url: String,
    reference: String,
    sha: String,
}

/// A single native package entry in the TOML lockfile (ADR 0072 Phase 2).
///
/// A hex entry has `version`; a git entry has `git` (and its `sha` is the
/// commit SHA rather than a hex checksum).
#[derive(Debug, Serialize, Deserialize)]
#[allow(dead_code)] // Constructed by serde deserialization
struct TomlNativePackageEntry {
    name: String,
    #[serde(default)]
    version: Option<String>,
    #[serde(default)]
    git: Option<String>,
    /// The manifest reference a git entry was resolved from.
    #[serde(default)]
    reference: Option<String>,
    /// The hex package name, when it differs from `name` (an alias).
    #[serde(default)]
    package: Option<String>,
    /// The hex outer checksum (`pkg_hash_ext`).
    #[serde(default)]
    outer_sha: Option<String>,
    /// rebar3's dependency level (0 = direct).
    #[serde(default)]
    level: Option<u32>,
    sha: String,
}

impl Lockfile {
    /// Create an empty lockfile.
    pub fn new() -> Self {
        Self {
            packages: BTreeMap::new(),
            native_packages: BTreeMap::new(),
        }
    }

    /// Add or update a git lock entry.
    pub fn insert(&mut self, entry: LockEntry) {
        self.packages.insert(entry.name.clone(), entry);
    }

    /// Add or update a native (hex) package lock entry.
    pub fn insert_native(&mut self, entry: NativePackageLock) {
        self.native_packages.insert(entry.name.clone(), entry);
    }

    /// Look up a git lock entry by dependency name.
    pub fn get(&self, name: &str) -> Option<&LockEntry> {
        self.packages.get(name)
    }

    /// Look up a native (hex) package lock entry by name.
    pub fn get_native(&self, name: &str) -> Option<&NativePackageLock> {
        self.native_packages.get(name)
    }

    /// Returns `true` if the lockfile contains no entries of any kind.
    pub fn is_empty(&self) -> bool {
        self.packages.is_empty() && self.native_packages.is_empty()
    }

    /// Returns `true` if the lockfile contains native (hex) package entries.
    pub fn has_native_packages(&self) -> bool {
        !self.native_packages.is_empty()
    }

    /// Remove all native package entries (used before re-populating from rebar3).
    pub fn clear_native_packages(&mut self) {
        self.native_packages.clear();
    }

    /// Collect all native (hex) dependency names from the lockfile.
    ///
    /// ADR 0072: After a build with `[native.dependencies]`,
    /// `beamtalk.lock` contains all resolved hex packages — including
    /// transitive hex deps (e.g., ranch via cowboy) and hex deps from
    /// transitive BT dependencies. This is the authoritative source for
    /// which OTP applications need startup at runtime.
    ///
    /// Returns an empty vec if no lockfile exists. Propagates read/parse
    /// errors so callers can surface lockfile corruption instead of
    /// silently skipping OTP app startup.
    pub fn collect_hex_dep_names(project_root: &Utf8Path) -> Result<Vec<String>> {
        match Self::read(project_root)? {
            Some(lock) => Ok(lock.native_packages.keys().cloned().collect()),
            None => Ok(Vec::new()),
        }
    }

    /// Read a lockfile from disk.
    ///
    /// Returns `None` if the file does not exist. Returns an error if the
    /// file exists but cannot be parsed.
    pub fn read(project_root: &Utf8Path) -> Result<Option<Self>> {
        let path = project_root.join(LOCKFILE_NAME);
        if !path.exists() {
            return Ok(None);
        }

        let content = std::fs::read_to_string(&path)
            .into_diagnostic()
            .wrap_err_with(|| format!("Failed to read lockfile '{path}'"))?;

        let lockfile =
            Self::parse(&content).wrap_err_with(|| format!("Failed to parse lockfile '{path}'"))?;

        Ok(Some(lockfile))
    }

    /// Parse lockfile content from a string.
    pub fn parse(content: &str) -> Result<Self> {
        let toml_lock: TomlLockfile = toml::from_str(content)
            .into_diagnostic()
            .wrap_err("Invalid lockfile format")?;

        let mut packages = BTreeMap::new();
        for entry in toml_lock.package {
            let reference = parse_reference(&entry.reference).wrap_err_with(|| {
                format!(
                    "Invalid reference '{}' for package '{}'",
                    entry.reference, entry.name
                )
            })?;

            let registry_version = entry.version.map(|version| RegistryVersion {
                version,
                registry: entry.registry,
            });

            packages.insert(
                entry.name.clone(),
                LockEntry {
                    name: entry.name,
                    url: entry.url,
                    reference,
                    resolved_sha: entry.sha,
                    registry_version,
                },
            );
        }

        let mut native_packages = BTreeMap::new();
        for entry in toml_lock.native_package {
            let source = match (entry.version, entry.git) {
                (Some(version), None) => NativeLockSource::Hex {
                    package: entry.package.unwrap_or_else(|| entry.name.clone()),
                    version,
                    checksum: entry.sha,
                    outer_checksum: entry.outer_sha,
                },
                (None, Some(url)) => NativeLockSource::Git {
                    url,
                    reference: entry
                        .reference
                        .as_deref()
                        .map(parse_reference)
                        .transpose()
                        .wrap_err_with(|| {
                            format!("Invalid reference for native package '{}'", entry.name)
                        })?,
                    sha: entry.sha,
                },
                _ => miette::bail!(
                    "Invalid native package '{}' — expected exactly one of 'version' or 'git'",
                    entry.name
                ),
            };
            native_packages.insert(
                entry.name.clone(),
                NativePackageLock {
                    name: entry.name,
                    level: entry.level,
                    source,
                },
            );
        }

        Ok(Self {
            packages,
            native_packages,
        })
    }

    /// Write the lockfile to disk.
    ///
    /// If the lockfile has no entries (no git or native deps), the file is
    /// removed to keep the project directory clean.
    pub fn write(&self, project_root: &Utf8Path) -> Result<()> {
        let path = project_root.join(LOCKFILE_NAME);

        if self.is_empty() {
            // Remove stale lockfile if no deps of any kind
            if path.exists() {
                std::fs::remove_file(&path)
                    .into_diagnostic()
                    .wrap_err_with(|| format!("Failed to remove empty lockfile '{path}'"))?;
            }
            return Ok(());
        }

        let content = self.serialize();
        std::fs::write(&path, content)
            .into_diagnostic()
            .wrap_err_with(|| format!("Failed to write lockfile '{path}'"))?;

        Ok(())
    }

    /// Serialize the lockfile to a string.
    pub fn serialize(&self) -> String {
        let mut output = String::new();
        output.push_str(LOCKFILE_HEADER);
        output.push('\n');

        for entry in self.packages.values() {
            output.push_str("[[package]]\n");
            let _ = writeln!(output, "name = \"{}\"", entry.name);
            if let Some(rv) = &entry.registry_version {
                let _ = writeln!(output, "version = \"{}\"", rv.version);
                if let Some(registry) = &rv.registry {
                    let _ = writeln!(output, "registry = \"{}\"", escape_toml_string(registry));
                }
            }
            let _ = writeln!(output, "url = \"{}\"", entry.url);
            let _ = writeln!(
                output,
                "reference = \"{}\"",
                format_reference(&entry.reference)
            );
            let _ = writeln!(output, "sha = \"{}\"", entry.resolved_sha);
            output.push('\n');
        }

        for entry in self.native_packages.values() {
            // Every field comes from rebar3's output, so escape them all.
            output.push_str("[[native_package]]\n");
            let _ = writeln!(output, "name = \"{}\"", escape_toml_string(&entry.name));
            match &entry.source {
                NativeLockSource::Hex {
                    package,
                    version,
                    checksum,
                    outer_checksum,
                } => {
                    if package != &entry.name {
                        let _ = writeln!(output, "package = \"{}\"", escape_toml_string(package));
                    }
                    let _ = writeln!(output, "version = \"{}\"", escape_toml_string(version));
                    let _ = writeln!(output, "sha = \"{}\"", escape_toml_string(checksum));
                    if let Some(outer) = outer_checksum {
                        let _ = writeln!(output, "outer_sha = \"{}\"", escape_toml_string(outer));
                    }
                }
                NativeLockSource::Git {
                    url,
                    reference,
                    sha,
                } => {
                    let _ = writeln!(output, "git = \"{}\"", escape_toml_string(url));
                    if let Some(reference) = reference {
                        let _ = writeln!(
                            output,
                            "reference = \"{}\"",
                            escape_toml_string(&format_reference(reference))
                        );
                    }
                    let _ = writeln!(output, "sha = \"{}\"", escape_toml_string(sha));
                }
            }
            if let Some(level) = entry.level {
                let _ = writeln!(output, "level = {level}");
            }
            output.push('\n');
        }

        output
    }
}

impl Default for Lockfile {
    fn default() -> Self {
        Self::new()
    }
}

/// Format a `GitReference` for lockfile storage.
///
/// Uses `type:value` format: `tag:v1.0.0`, `branch:main`, `rev:abc1234`.
fn format_reference(reference: &GitReference) -> String {
    match reference {
        GitReference::Tag(tag) => format!("tag:{tag}"),
        GitReference::Branch(branch) => format!("branch:{branch}"),
        GitReference::Rev(rev) => format!("rev:{rev}"),
    }
}

/// Parse a lockfile reference string back to a `GitReference`.
fn parse_reference(s: &str) -> Result<GitReference> {
    if let Some(tag) = s.strip_prefix("tag:") {
        Ok(GitReference::Tag(tag.to_string()))
    } else if let Some(branch) = s.strip_prefix("branch:") {
        Ok(GitReference::Branch(branch.to_string()))
    } else if let Some(rev) = s.strip_prefix("rev:") {
        Ok(GitReference::Rev(rev.to_string()))
    } else {
        miette::bail!(
            "Invalid reference format '{s}' — expected 'tag:...', 'branch:...', or 'rev:...'"
        );
    }
}

/// Parse a rebar3 lockfile (`rebar.lock`) into locked packages: hex
/// versions and checksums, git commit SHAs, and each entry's level.
///
/// rebar3 writes the lockfile in Erlang term format:
///
/// ```erlang
/// {"1.2.0",
/// [{<<"cowboy">>,{pkg,<<"cowboy">>,<<"2.12.0">>},0},
///  {<<"oidcc">>,
///   {git,"https://github.com/jamesc/oidcc",
///        {ref,"0123abcd..."}},
///   0}]}.
/// [
/// {pkg_hash,[{<<"cowboy">>,<<"INNER">>}]},
/// {pkg_hash_ext,[{<<"cowboy">>,<<"OUTER">>}]}
/// ].
/// ```
///
/// We parse this with simple string scanning rather than a full Erlang term
/// parser — the format is stable and well-defined. `{git_subdir, ...}` and
/// other source kinds are skipped: the manifest cannot declare them, so they
/// only appear transitively and simply re-resolve.
pub fn parse_rebar_lock(content: &str) -> Vec<NativePackageLock> {
    let compact = compact_rebar_lock(content);
    let checksums = extract_hash_section(&compact, "pkg_hash");
    let outer_checksums = extract_hash_section(&compact, "pkg_hash_ext");

    let mut packages: Vec<NativePackageLock> = extract_lock_entries(&compact)
        .into_iter()
        .map(|entry| {
            let source = match entry.source {
                RebarLockSource::Pkg { package, version } => NativeLockSource::Hex {
                    checksum: checksums.get(&entry.name).cloned().unwrap_or_default(),
                    outer_checksum: outer_checksums.get(&entry.name).cloned(),
                    package,
                    version,
                },
                RebarLockSource::Git { url, sha } => NativeLockSource::Git {
                    url,
                    reference: None,
                    sha,
                },
            };
            NativePackageLock {
                name: entry.name,
                level: entry.level,
                source,
            }
        })
        .collect();

    packages.sort_by(|a, b| a.name.cmp(&b.name));
    packages
}

/// rebar.lock with all whitespace removed. rebar3 pretty-prints entries
/// across lines; names, versions, URLs and SHAs contain no whitespace, so
/// the scanner can match each entry's shape exactly.
fn compact_rebar_lock(content: &str) -> String {
    content.chars().filter(|c| !c.is_whitespace()).collect()
}

/// One dependency entry of rebar.lock's first term.
struct RebarLockEntry {
    name: String,
    source: RebarLockSource,
    level: Option<u32>,
}

enum RebarLockSource {
    Pkg { package: String, version: String },
    Git { url: String, sha: String },
}

/// Text between the start of `s` and the next `"`, and the rest after it.
fn take_quoted(s: &str) -> Option<(&str, &str)> {
    let end = s.find('"')?;
    Some((&s[..end], &s[end + 1..]))
}

/// The level that closes an entry: `,N}` after the source tuple's `}`.
fn trailing_level(rest: &str) -> Option<u32> {
    let after = &rest[rest.find("},")? + 2..];
    let digits: String = after.chars().take_while(char::is_ascii_digit).collect();
    digits.parse().ok()
}

/// Extract the dependency entries of rebar.lock (compacted). Each entry is
/// matched in place — its source tuple must follow its own name — so an
/// entry of one kind is never stitched onto the next.
fn extract_lock_entries(compact: &str) -> Vec<RebarLockEntry> {
    const ENTRY_OPEN: &str = "{<<\"";
    const PKG_OPEN: &str = ">>,{pkg,<<\"";
    const GIT_OPEN: &str = ">>,{git,\"";

    let mut results = Vec::new();
    let mut rest = compact;

    while let Some(start) = rest.find(ENTRY_OPEN) {
        rest = &rest[start + ENTRY_OPEN.len()..];
        let Some((name, after_name)) = take_quoted(rest) else {
            break;
        };
        let parsed = if let Some(pkg) = after_name.strip_prefix(PKG_OPEN) {
            // {pkg,<<"package">>,<<"version">>[,...]}
            take_quoted(pkg).and_then(|(package, after_package)| {
                let version_part = after_package.strip_prefix(">>,<<\"")?;
                let (version, tail) = take_quoted(version_part)?;
                Some((
                    RebarLockSource::Pkg {
                        package: package.to_string(),
                        version: version.to_string(),
                    },
                    tail,
                ))
            })
        } else if let Some(git) = after_name.strip_prefix(GIT_OPEN) {
            // {git,"url",{ref,"sha"}}
            take_quoted(git).and_then(|(url, after_url)| {
                let sha_part = after_url.strip_prefix(",{ref,\"")?;
                let (sha, tail) = take_quoted(sha_part)?;
                Some((
                    RebarLockSource::Git {
                        url: url.to_string(),
                        sha: sha.to_string(),
                    },
                    tail,
                ))
            })
        } else {
            None
        };
        let Some((source, tail)) = parsed else {
            continue;
        };
        results.push(RebarLockEntry {
            name: name.to_string(),
            level: trailing_level(tail),
            source,
        });
        rest = tail;
    }

    results
}

/// Extract `{<<"name">>,<<"HASH">>}` pairs from rebar.lock's
/// `{section,[...]}` (`pkg_hash` or `pkg_hash_ext`), compacted.
fn extract_hash_section(compact: &str, section: &str) -> BTreeMap<String, String> {
    let mut hashes = BTreeMap::new();
    let open = format!("{{{section},[");
    let Some(start) = compact.find(&open) else {
        return hashes;
    };
    let body = &compact[start + open.len()..];
    let body = &body[..body.find("]}").unwrap_or(body.len())];

    let mut rest = body;
    while let Some(start) = rest.find("{<<\"") {
        rest = &rest[start + 4..];
        let Some((name, after_name)) = take_quoted(rest) else {
            break;
        };
        let Some(hash_part) = after_name.strip_prefix(">>,<<\"") else {
            continue;
        };
        let Some((hash, tail)) = take_quoted(hash_part) else {
            break;
        };
        hashes.insert(name.to_string(), hash.to_string());
        rest = tail;
    }
    hashes
}

/// Render a rebar3 `rebar.lock` from locked native packages — the inverse
/// of [`parse_rebar_lock`].
///
/// rebar3 treats `rebar.lock` as authoritative: a locked dependency is
/// fetched (or an existing checkout moved) to the locked version or commit,
/// whatever `rebar.config` says. Writing it from `beamtalk.lock` before
/// running rebar3 therefore pins every locked package — direct and
/// transitive — on a fresh checkout too. An entry without a recorded level
/// is written as level 0 when `direct` names it, else level 1.
pub fn render_rebar_lock<'a>(
    packages: impl IntoIterator<Item = &'a NativePackageLock>,
    direct: &dyn Fn(&str) -> bool,
) -> String {
    use crate::beam_compiler::escape_erlang_string as esc;

    let mut entries = Vec::new();
    let mut hashes = Vec::new();
    let mut outer_hashes = Vec::new();
    for pkg in packages {
        let name = esc(&pkg.name);
        let level = pkg.level.unwrap_or(u32::from(!direct(&pkg.name)));
        match &pkg.source {
            NativeLockSource::Hex {
                package,
                version,
                checksum,
                outer_checksum,
            } => {
                entries.push(format!(
                    "{{<<\"{name}\">>,{{pkg,<<\"{}\">>,<<\"{}\">>}},{level}}}",
                    esc(package),
                    esc(version)
                ));
                if !checksum.is_empty() {
                    hashes.push(format!("{{<<\"{name}\">>,<<\"{}\">>}}", esc(checksum)));
                }
                if let Some(outer) = outer_checksum {
                    outer_hashes.push(format!("{{<<\"{name}\">>,<<\"{}\">>}}", esc(outer)));
                }
            }
            NativeLockSource::Git { url, sha, .. } => entries.push(format!(
                "{{<<\"{name}\">>,{{git,\"{}\",{{ref,\"{}\"}}}},{level}}}",
                esc(url),
                esc(sha)
            )),
        }
    }

    let mut attrs = vec![format!("{{pkg_hash,[\n {}]}}", hashes.join(",\n "))];
    if !outer_hashes.is_empty() {
        attrs.push(format!(
            "{{pkg_hash_ext,[\n {}]}}",
            outer_hashes.join(",\n ")
        ));
    }
    format!(
        "{{\"1.2.0\",\n[{}]}}.\n[\n{}\n].\n",
        entries.join(",\n "),
        attrs.join(",\n")
    )
}

/// Read and parse the rebar3 lockfile from the build directory.
///
/// rebar3 writes `rebar.lock` in the directory where it runs
/// (`_build/dev/native/`).
pub fn read_rebar_lock(rebar_base_dir: &Utf8Path) -> Result<Vec<NativePackageLock>> {
    let lock_path = rebar_base_dir.join("rebar.lock");
    if !lock_path.exists() {
        return Ok(Vec::new());
    }

    let content = std::fs::read_to_string(&lock_path)
        .into_diagnostic()
        .wrap_err_with(|| format!("Failed to read rebar.lock at '{lock_path}'"))?;

    Ok(parse_rebar_lock(&content))
}

