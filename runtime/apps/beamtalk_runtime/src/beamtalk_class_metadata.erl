Walks the ancestors' published `defines_user_class_new0` facts, not `Name`'s
own (a class's own `new` is already what its `new/0` delegates to). Unlike
`chain_has_user_new1/1` this fails *open*: an unpublished fact (an older
module or a dynamic ancestor), a missing row, a missing superclass link or a
cycle stop the walk with `false`, which is the behaviour before the fact
existed. `Value` and `Actor` publish `false` (their root `new` definitions
are the standard constructor and the `Use spawn` error).

Memoised as `{chain_has_user_new0, Name}` in `beamtalk_class_derived_cache`,
flushed by every class-metadata write, so an ancestor reloaded with or without
a user `new` is re-read by its descendants.
""".
-spec chain_has_user_new0(class_name()) -> boolean().
chain_has_user_new0(Name) ->
    beamtalk_class_derived_cache:fetch({chain_has_user_new0, Name}, fun() ->
        case lookup_superclass(Name) of
            {ok, Super} -> {cache, ancestors_have_user_new0(Super)};
            not_found -> {nocache, false}
        end
    end).

-doc """
Whether `Name` has no `new` of its own and inherits a user class-side `new`
(BT-4479): the one rule both the class process's `{new, []}` handler
(`beamtalk_object_class`) and the direct constructor verdict
(`beamtalk_class_dispatch:lookup_direct_constructor/3`) apply, so the two
paths run the same `new`. A class whose own `defines_user_class_new0` is
`true` has its own `class new`, which dispatch finds first, so the chain is
not consulted for it.
""".
-spec inherits_user_class_new(class_name()) -> boolean().
inherits_user_class_new(Name) ->
    lookup_defines_user_class_new0(Name) =/= true andalso chain_has_user_new0(Name).

-spec ancestors_have_user_new0(superclass()) -> boolean().
ancestors_have_user_new0(Start) ->
    StepFun = fun(Class, _Depth) ->
        case lookup_defines_user_class_new0(Class) of
            true ->
                {found, true};
            _ ->
                case lookup_superclass(Class) of
                    {ok, Super} -> {next, Super};
                    not_found -> not_found
                end
        end
    end,
    %% `not_found` (top of the chain) and `{max_depth_exceeded, _}` (a cycle)
    %% both fail open.
    beamtalk_hierarchy:walk_ancestors(Start, StepFun, ?MAX_HIERARCHY_DEPTH) =:= {found, true}.

-doc "Read a class's whole direct-construction eligibility set (`[]` when none or unknown).".
-spec lookup_direct_constructors(class_name()) -> [selector()].
lookup_direct_constructors(Name) ->
    case field(Name, #class_metadata.direct_constructors) of
        Ctors when is_list(Ctors) -> Ctors;
        _ -> []
    end.

-doc """
Resolve a constructor to a direct-callable module for a class,
or `error` when the send must go through the class gen_server.

The row must name a module, the class must have no runtime-installed
class-method funs (ADR 0084), and the baked verdict must list the selector.
The target is always `new` itself (`new/0` for `new`, `new/1` for `new:`) —
the caller checks the export at the right arity.
""".
-spec lookup_direct_constructor(class_name(), selector()) -> {ok, module()} | error.
lookup_direct_constructor(Name, Selector) ->
    case row(Name) of
        {ok, #class_metadata{
            module = Module,
            has_runtime_class_methods = false,
            direct_constructors = Ctors
        }} when Module =/= undefined, is_list(Ctors) ->
            case lists:member(Selector, Ctors) of
                true -> {ok, Module};
                false -> error
            end;
        _ ->
            error
    end.

-doc """
Fetch a runtime class-method fun for `{DefiningClass, Selector}`.

Gated on the per-class `has_runtime_class_methods` flag: a compile-time-only
class returns `error` without ever reading the funs table (the hot-path
guarantee). Returns `{ok, #{block, arity}}` when a runtime fun is installed.
""".
-spec lookup_class_method_fun(class_name(), selector()) ->
    {ok, class_method_fun_info()} | error.
lookup_class_method_fun(Name, Selector) ->
    case has_runtime_class_methods(Name) of
        false ->
            error;
        true ->
            try ets:lookup(?FUN_TABLE, {Name, Selector}) of
                [{_, Info}] -> {ok, Info};
                [] -> error
            catch
                error:badarg -> error
            end
    end.

-doc """
Remove every runtime class-method fun installed for `Name`.

Called on class teardown (`delete/1`) and before re-seeding on `update_class`
reload, so memory-only runtime methods do not survive a recompile (ADR 0082).
""".
-spec delete_class_method_funs(class_name()) -> ok.
delete_class_method_funs(Name) ->
    case ets:info(?FUN_TABLE) of
        undefined ->
            ok;
        _ ->
            try
                ets:match_delete(?FUN_TABLE, {{Name, '_'}, '_'}),
                ok
            catch
                error:badarg -> ok
            end
    end.

-doc """
Remove the one runtime class-method fun installed for `{Name, Selector}`
(BT-4438, `X class removeSelector:`), leaving the class's other funs alone.

The caller publishes the class's new selector set first
(`set_class_method_selectors/2`) and closes the gate afterwards
(`reset_runtime_class_methods/1`) if no funs remain. Drops derived facts
(the class-method owner memo) after the delete, as `set_runtime_class_methods/2`
does after an install. A no-op if the table or row is absent.
""".
-spec delete_class_method_fun(class_name(), selector()) -> ok.
delete_class_method_fun(Name, Selector) ->
    case ets:info(?FUN_TABLE) of
        undefined ->
            ok;
        _ ->
            try
                ets:delete(?FUN_TABLE, {Name, Selector})
            catch
                error:badarg -> ok
            end
    end,
    beamtalk_class_derived_cache:invalidate().

-doc """
Publish the class's local class-side selector set without touching the
runtime-fun gate (BT-4438). Used by a runtime-fun removal, which publishes the
restored selector set before deleting the fun. A no-op if the row is absent.
""".
-spec set_class_method_selectors(class_name(), [selector()]) -> ok.
set_class_method_selectors(Name, Selectors) ->
    new(),
    try
        ets:update_element(?TABLE, Name, [{#class_metadata.selectors, Selectors}])
    catch
        error:badarg -> ok
    end,
    beamtalk_class_derived_cache:invalidate().

-doc """
Read the per-class "has runtime class methods" gate flag.

`false` (the default for compile-time-only classes) means dispatch skips the
funs-table read entirely. Exposed for dispatch gating and tests.
""".
-spec has_runtime_class_methods(class_name()) -> boolean().
has_runtime_class_methods(Name) ->
    case field(Name, #class_metadata.has_runtime_class_methods) of
        true -> true;
        _ -> false
    end.

-doc """
Atomically publish the class's local selectors and set the gate flag.

Used by `init`/`update_class` seeding and live `put_class_method`: the funs are
written first (`put_class_method_fun/3`), then this single `update_element`
publishes the new selector set together with the gate flag, so a concurrent
reader never observes a discoverable selector whose gate is still closed.
Leaves `module` and `superclass` untouched. A no-op if the row is absent.
""".
-spec set_runtime_class_methods(class_name(), [selector()]) -> ok.
set_runtime_class_methods(Name, Selectors) ->
    new(),
    %% BT-3669: raise the compiled-fast-path shadow flag before the gate opens.
    beamtalk_class_shadow_flags:set(runtime_fun, Name),
    try
        ets:update_element(?TABLE, Name, [
            {#class_metadata.selectors, Selectors},
            {#class_metadata.has_runtime_class_methods, true}
        ])
    catch
        error:badarg -> ok
    end,
    %% ADR 0142 §2 (BT-4299): a runtime fun at an ancestor changes what a
    %% descendant's send resolves to without touching the descendant's own
    %% flag, so derived facts (the class-method owner memo) must go, as
    %% `beamtalk_extensions:register/remove` already do. Only after the row has
    %% landed (see beamtalk_class_derived_cache).
    beamtalk_class_derived_cache:invalidate().

-doc """
Explicitly clear the "has runtime class methods" gate, independent of any
other field.

Pairs with `delete_class_method_funs/1` when purging a class's funs
table ahead of a reload — together they are the reload path's explicit,
self-documenting substitute for a full-row overwrite's implicit reset
(see `merge_identity/5`, which deliberately leaves the gate alone).
A no-op if the row is absent.
""".
-spec reset_runtime_class_methods(class_name()) -> ok.
reset_runtime_class_methods(Name) ->
    new(),
    try
        ets:update_element(?TABLE, Name, [
            {#class_metadata.has_runtime_class_methods, false}
        ])
    catch
        error:badarg -> ok
    end,
    %% BT-3669: clear the flag only after the gate is closed.
    beamtalk_class_shadow_flags:clear(runtime_fun, Name),
    ok.

