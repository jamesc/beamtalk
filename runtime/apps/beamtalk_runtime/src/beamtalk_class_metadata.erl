""".
-spec foldl_modules(fun(({class_name(), module()}, Acc) -> Acc), Acc) -> Acc.
foldl_modules(Fun, Acc0) ->
    case ets:info(?TABLE) of
        undefined ->
            Acc0;
        _ ->
            try
                ets:foldl(
                    fun
                        (#class_metadata{module = undefined}, Acc) -> Acc;
