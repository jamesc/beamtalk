-doc "Look up a class's module name. `undefined`/missing yields `not_found`.".
-spec lookup_module(class_name()) -> {ok, module()} | not_found.
lookup_module(Name) ->
    case field(Name, #class_metadata.module) of
        undefined -> not_found;
        Module -> {ok, Module}
    end.

-doc """
Look up a class's module and local class-method selectors.

Returns `{ok, Module, Selectors}` only when both fields have been written (an
empty selector list is valid); otherwise `not_found`. The two are always written
together (`insert/4`), so requiring a non-`undefined` module keeps the return
honest with the `module()` spec even if a row carries only one of them.
""".
-spec lookup_methods(class_name()) -> {ok, module(), [selector()]} | not_found.
lookup_methods(Name) ->
    case row(Name) of
        {ok, #class_metadata{module = undefined}} -> not_found;
        {ok, #class_metadata{selectors = undefined}} -> not_found;
        {ok, #class_metadata{module = Module, selectors = Selectors}} -> {ok, Module, Selectors};
        not_found -> not_found
    end.

-doc """
Look up a class's superclass.

Returns `{ok, none}` for a root class and `{ok, Super}` otherwise; `not_found`
when the superclass field has not been written.
""".
-spec lookup_superclass(class_name()) -> {ok, superclass()} | not_found.
lookup_superclass(Name) ->
    case field(Name, #class_metadata.superclass) of
        undefined -> not_found;
        Super -> {ok, Super}
    end.

-doc """
Look up whether a class is abstract (BT-3047 / ADR 0109 amendment).

Returns `not_found` — never a defaulted boolean — when the row or field is
unset. Callers that use this to gate instantiation (e.g.
`beamtalk_class_instantiation:resolve_is_abstract_or_raise/2`) must not
silently pick either boolean on a miss: `false` would let a genuinely abstract
class be constructed if the row hasn't been written yet, and `true` would
wrongly refuse a genuinely concrete one. A miss should never happen for a live,
already-dispatching class (the row is written unconditionally at the same
`init`/reload point that establishes the class's other identity), so `not_found`
here indicates a bug worth surfacing loudly rather than a normal case to paper
over with a default.
""".
-spec lookup_is_abstract(class_name()) -> {ok, boolean()} | not_found.
lookup_is_abstract(Name) ->
    case field(Name, #class_metadata.is_abstract) of
        undefined -> not_found;
        IsAbstract -> {ok, IsAbstract}
    end.

-doc """
Return all class names whose direct superclass is `Name`.

BT-3221: an indexed `ets:lookup/2` on the `beamtalk_class_subclass_index`
reverse-edge table, not a full-table scan of `?TABLE` — O(subclass count)
instead of O(loaded-class count). Returns `[]` if the index table does not
exist (mirrors the old table-absent contract, now against the table this
function actually reads).
""".
-spec match_subclasses(class_name()) -> [class_name()].
match_subclasses(Name) ->
    case ets:info(?SUBCLASS_INDEX) of
        undefined ->
            [];
        _ ->
            try
                [ClassName || {_Superclass, ClassName} <- ets:lookup(?SUBCLASS_INDEX, Name)]
            catch
                error:badarg -> []
            end
    end.

-doc """
Fold over `{ClassName, Superclass}` pairs for every row with a known superclass.

Rows whose superclass field is unset (`undefined`) are skipped, preserving the
behaviour of the former hierarchy table, which only contained rows that had a
superclass written. Returns `Acc0` if the table does not exist.
""".
-spec foldl(fun(({class_name(), superclass()}, Acc) -> Acc), Acc) -> Acc.
foldl(Fun, Acc0) ->
    case ets:info(?TABLE) of
        undefined ->
            Acc0;
        _ ->
            try
                ets:foldl(
                    fun
                        (#class_metadata{superclass = undefined}, Acc) -> Acc;
                        (#class_metadata{name = N, superclass = S}, Acc) -> Fun({N, S}, Acc)
                    end,
                    Acc0,
                    ?TABLE
                )
            catch
                error:badarg -> Acc0
            end
    end.

-doc """
Fold over `{ClassName, Module}` pairs for every row with a known module.

BT-3081: gives `beamtalk_class_registry:module_to_class_map/0` an ETS-only
(no gen_server calls) way to build the module→class map, instead of scanning
every live class process via `live_class_entries/0`. Rows whose module field
