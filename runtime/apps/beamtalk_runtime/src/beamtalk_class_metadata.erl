-record(class_metadata, {
    name :: class_name(),
    module :: module() | undefined,
    selectors :: [selector()] | undefined,
    superclass :: superclass() | undefined,
    %% ADR 0084: true once a runtime/builder class-method fun has been
    %% installed for this class. The dispatch-time gate: false means the funs
    %% table is never read for this class.
    has_runtime_class_methods = false :: boolean(),
    %% ADR 0109 amendment: whether the class is abstract, read by the
    %% instantiation intrinsics (`self spawn`/`self spawnWith:`/etc.) instead of
    %% the `beamtalk_class_is_abstract` process-dictionary flag, which resolves
    %% against the wrong class when read from inside a block executing in a
    %% foreign class's process. `undefined` (the "field never written" sentinel,
    %% not a boolean default — see `lookup_is_abstract/1`) rather than `false`,
    %% because a class-existence guard must not silently default toward
    %% *permitting* instantiation on a lookup miss.
    is_abstract :: boolean() | undefined,
    %% ADR 0129 Phase 0b: `direct_class_methods` from the compiled module's
    %% `__beamtalk_meta/0` — selector => safe class-method function name, for
    %% the class methods `compute_direct_call_eligible` (Rust) deemed callable
    %% without the class gen_server. Empty for dynamic classes, classes with
    %% class state, and modules compiled before the key existed.
    direct_class_methods = #{} :: #{selector() => atom()},
    %% BT-3826: the class process's reflection state, mirrored here so another
    %% class process (or anything else) can read it without a blocking
    %% `gen_server:call` into the owning class. Written only by
    %% `put_reflection/2`; `undefined` until the owning class publishes it
    %% (`init/1` publishes before the class is observable as registered).
    instance_methods :: [selector()] | undefined,
    instance_variables :: [atom()] | undefined,
    method_return_types :: #{selector() => term()} | undefined,
    class_method_return_types :: #{selector() => term()} | undefined,
    %% BT-3832: class flags, mirrored from the class process like the
    %% reflection state above. Written only by `put_flags/2`; `undefined`
    %% until the owning class publishes. (`is_abstract` above is the same
    %% kind of flag, written with the identity fields.)
    is_sealed :: boolean() | undefined,
    is_typed :: boolean() | undefined,
    is_internal :: boolean() | undefined,
    shape_version :: pos_integer() | undefined,
    %% `direct_constructors` from the compiled module's
    %% `__beamtalk_meta/0` — the `[new]` / `[new, 'new:']` subset
    %% `direct_constructors` (Rust) deemed buildable in the caller without
    %% the class gen_server. A plain list (at most two elements); `[]` for
    %% dynamic classes, stateful classes, and modules compiled before the
    %% key existed.
    direct_constructors = [] :: [selector()]
}).

-type side() :: instance | class.
-type method_record() :: #{
    info := map(),
    source := binary(),
    signature := term(),
    doc := term()
}.
