-doc """
Ensure the unified class metadata ETS table exists (idempotent).

Creates the table on first call; subsequent calls retroactively set the heir
once the supervisor is alive. Safe to call concurrently — a try/catch
handles the race between `ets:info/1` and `ets:new/2`.
""".
-spec new() -> ok.
new() ->
    %% BT-4064: the derived-fact cache (resolved dispatch module, Exception
    %% bit, ...) lives and dies with this table. A freshly (re)created table has
    %% no rows, so anything cached against the old one is stale.
    ok = beamtalk_class_derived_cache:new(),
    case ets:info(?TABLE, owner) of
        undefined -> beamtalk_class_derived_cache:invalidate();
        _ -> ok
    end,
    ensure_table(?TABLE, [
        set,
        public,
        named_table,
        {keypos, #class_metadata.name},
        {read_concurrency, true}
    ]),
    %% The funs table is a plain {Key, Value} set (default keypos 1),
    %% Key = {DefiningClass, Selector}, Value = #{block, arity}.
    ensure_table(?FUN_TABLE, [
        set,
        public,
        named_table,
        {read_concurrency, true}
    ]),
    %% Reverse-edge index, {Superclass, ClassName} rows, default
    %% keypos 1 (Superclass). `bag` because a superclass has many subclasses.
    ensure_table(?SUBCLASS_INDEX, [
        bag,
        public,
        named_table,
        {read_concurrency, true}
    ]),
    %% BT-3832: per-method records, {{Class, Side, Selector}, Record}.
    ensure_table(?METHOD_RECORDS, [
        ordered_set,
        public,
        named_table,
        {read_concurrency, true}
    ]),
    ok.

-spec ensure_table(atom(), [term()]) -> ok.
ensure_table(Table, Opts) ->
    case ets:info(Table) of
        undefined ->
            try
                ets:new(Table, Opts ++ beamtalk_ets_heir:heir_option()),
                ok
            catch
                error:badarg -> ok
            end;
        _ ->
            beamtalk_ets_heir:maybe_set_heir(Table),
            ok
    end.

