-doc """
Publish one side's per-method records for `Name` (BT-3832), replacing whatever
that side held.

The new rows are written first and only then are rows for selectors that are
no longer present deleted, so a concurrent reader sees the old or the new
record for a still-present selector, never a gap.
""".
-spec put_method_records(class_name(), side(), #{selector() => method_record()}) -> ok.
put_method_records(Name, Side, Records) ->
    %% BT-4473: a watched selector defined below `Object` is raised before
    %% the record can be seen (`beamtalk_default_method:note_override/2`).
    case Side of
        instance -> beamtalk_default_method:note_overrides(Name, Records);
        class -> ok
    end,
    write_method_records(Name, Side, Records),
    %% BT-4071: `beamtalk_method_resolver:instance_method_info/2` memoises
    %% instance-side resolution from these records; invalidate after the write
    %% lands. Class-side records feed no cached fact, so they don't flush it.
    case Side of
        instance -> beamtalk_class_derived_cache:invalidate();
        class -> ok
    end.

-spec write_method_records(class_name(), side(), #{selector() => method_record()}) -> ok.
write_method_records(Name, Side, Records) ->
    try
        ets:insert(
            ?METHOD_RECORDS,
            [{{Name, Side, Sel}, Rec} || Sel := Rec <- Records]
        ),
        Stale = [
            Sel
         || [Sel] <- ets:match(?METHOD_RECORDS, {{Name, Side, '$1'}, '_'}),
            not is_map_key(Sel, Records)
        ],
        lists:foreach(fun(Sel) -> ets:delete(?METHOD_RECORDS, {Name, Side, Sel}) end, Stale),
        ok
    catch
        error:badarg ->
            %% Table not created yet (or torn down): create it and retry once.
            new(),
            try
                ets:insert(
                    ?METHOD_RECORDS,
                    [{{Name, Side, Sel}, Rec} || Sel := Rec <- Records]
                ),
                ok
            catch
                error:badarg -> ok
            end
    end.

