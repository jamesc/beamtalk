-spec merge_ancestor_map(
    class_name(), fun((class_name()) -> #{atom() => term()}), #{atom() => term()}
) -> #{atom() => term()}.
merge_ancestor_map(StartSuper, ReadOwnMapFun, AccSoFar) ->
    StepFun = fun({CurrentClass, Acc}, _Depth) ->
        OwnMap =
            %% bt-catcher-audit: not-applicable-no-block - ReadOwnMapFun is a metadata read, not a
            %% Beamtalk block
            try
                ReadOwnMapFun(CurrentClass)
            catch
                _:_ -> #{}
            end,
        NewAcc = maps:merge(OwnMap, Acc),
        case lookup_superclass(CurrentClass) of
            {ok, none} -> {found, NewAcc};
            {ok, Super} -> {next, {Super, NewAcc}};
            not_found -> {found, NewAcc}
        end
    end,
    case beamtalk_hierarchy:walk_ancestors({StartSuper, AccSoFar}, StepFun, ?MAX_HIERARCHY_DEPTH) of
        {found, Result} ->
            Result;
        {max_depth_exceeded, {CycleClass, Partial}} ->
            ?LOG_WARNING(
                "flatten_ancestor_map: max hierarchy depth ~p exceeded at ~p — possible cycle",
                [?MAX_HIERARCHY_DEPTH, CycleClass],
                #{domain => [beamtalk, runtime]}
            ),
            Partial;
        not_found ->
            %% Unreachable: StepFun above always resolves to {found, _} — a
            %% `none` superclass or an unregistered ancestor is translated to
            %% a terminal {found, _}. walk_ancestors/3 only returns not_found
            %% for a `none` StartNode, and the only caller here
            %% (flatten_ancestor_map/2) never invokes merge_ancestor_map/3
            %% with StartSuper = none.
            AccSoFar
    end.

