-doc """
Insert or overwrite the **entire** metadata row for a class — row *creation*.

This is a full-row write, not a per-field merge: every call replaces all of
`module`, `selectors`, `superclass`, `is_abstract`, **and resets
`has_runtime_class_methods` to `false`**. The class gen_server calls this only
from `init/1`, where the row is genuinely new (or being recreated after
teardown), so resetting the gate is correct — a brand-new row has no runtime
funs installed yet. Pass `undefined` only to leave a field genuinely unset
(used by tests that exercise one field in isolation, and by callers that don't
know `is_abstract` — ADR 0109 amendment).

Do NOT call this to update an **existing** row — besides wiping any
field you don't pass explicitly, it silently drops
`has_runtime_class_methods`, discarding every runtime class method unless the
caller remembers a follow-up `seed_runtime_class_methods/2`. Use
`merge_identity/5` for updating an existing row instead; it never touches
the gate.
""".
-spec insert(
    class_name(),
    module() | undefined,
    [selector()] | undefined,
    superclass() | undefined,
    boolean() | undefined
) ->
    ok.
insert(Name, Module, Selectors, Superclass, IsAbstract) ->
    Row = #class_metadata{
        name = Name,
        module = Module,
        selectors = Selectors,
        superclass = Superclass,
        is_abstract = IsAbstract
    },
    new(),
    %% Read the row's previous superclass (undefined if there was no
    %% row yet) before overwriting it, so the subclass index can drop the
    %% stale edge from the old superclass if this call changes it.
    OldSuperclass = field(Name, #class_metadata.superclass),
    try
        ets:insert(?TABLE, Row),
        sync_subclass_index(Name, OldSuperclass, Superclass)
    catch
        error:badarg ->
            %% Table vanished between new/0 and ets:insert/2 — recreate and retry once.
            new(),
            ets:insert(?TABLE, Row),
            sync_subclass_index(Name, OldSuperclass, Superclass)
    end,
    %% BT-3669: a full-row write resets has_runtime_class_methods to false;
    %% clear the shadow flag only AFTER the gate is closed (a stale true is safe).
    beamtalk_class_shadow_flags:clear(runtime_fun, Name),
    %% BT-4064: only after the row has landed (see beamtalk_class_derived_cache).
    beamtalk_class_derived_cache:invalidate().

-doc """
Merge identity fields into an **existing** metadata row — row *update*.

Per-field update of `module`, `selectors`, `superclass`, and
`is_abstract` via `ets:update_element/3`; unlike `insert/5` it never touches
`has_runtime_class_methods`, so a caller that reloads a class's identity
cannot accidentally wipe its runtime class methods by forgetting a follow-up
`seed_runtime_class_methods/2` call. A caller that genuinely needs to drop the
gate (e.g. because it just purged the funs table via
`delete_class_method_funs/1`) must say so explicitly via
`reset_runtime_class_methods/1` — the two are never an implicit side effect of
each other.

Falls back to a full `insert/5` (gate defaults to `false`) if no row exists
yet for `Name` — the reload path this backs (`beamtalk_object_class:
apply_class_info/2`) always has a row already (the class went through
`init/1`), but this keeps the function correct standalone and in tests.
""".
-spec merge_identity(
    class_name(),
    module() | undefined,
    [selector()] | undefined,
    superclass() | undefined,
    boolean() | undefined
) ->
    ok.
merge_identity(Name, Module, Selectors, Superclass, IsAbstract) ->
    new(),
    %% Read the previous superclass before the update lands, so a
    %% re-register that changes superclass can drop the stale reverse edge
    %% from the old parent (see sync_subclass_index/3).
    OldSuperclass = field(Name, #class_metadata.superclass),
    %% ets:update_element/3 does NOT raise on a missing key — it returns
    %% `false` (only a missing/unwritable *table* raises badarg) — so the
    %% fallback to row creation must branch on the boolean return, not on a
    %% caught exception.
    try
        ets:update_element(?TABLE, Name, [
            {#class_metadata.module, Module},
            {#class_metadata.selectors, Selectors},
            {#class_metadata.superclass, Superclass},
            {#class_metadata.is_abstract, IsAbstract}
        ])
    of
        true ->
            sync_subclass_index(Name, OldSuperclass, Superclass),
            %% BT-4064: a hot reload / redefinition can move the class to
            %% another module or superclass; drop derived facts after the write.
            beamtalk_class_derived_cache:invalidate();
        false ->
            %% No existing row — fall back to row creation. A brand-new row
            %% has no funs to preserve, so insert/5's gate reset is correct.
            %% insert/5 re-reads the (still-absent) old superclass itself, so
            %% this never double-applies the index update.
            insert(Name, Module, Selectors, Superclass, IsAbstract)
    catch
        error:badarg ->
            %% Table vanished between new/0 and the update — recreate via insert/5.
            insert(Name, Module, Selectors, Superclass, IsAbstract)
    end.

-doc """
Remove a class's metadata row.

Called from the class gen_server `terminate/2`. Safe if the row — or the table —
does not exist.
""".
-spec delete(class_name()) -> ok.
delete(Name) ->
    %% Drop any runtime class-method funs alongside the metadata row so
    %% a class that is removed (or whose process terminates) leaves no stale
    %% dispatch entries behind.
    delete_class_method_funs(Name),
    delete_method_records(Name),
    beamtalk_class_shadow_flags:clear(runtime_fun, Name),
    %% Read the superclass before the row disappears, so the reverse
    %% edge {Superclass, Name} can be dropped from the subclass index too —
    %% otherwise Name would linger forever as a phantom subclass of its old
    %% superclass. This does NOT touch edges keyed on Name itself (i.e. rows
    %% for Name's own children) — those stay valid; a class's children remain
    %% discoverable even if its own row is gone (see moduledoc).
    OldSuperclass = field(Name, #class_metadata.superclass),
    try
        ets:delete(?TABLE, Name),
        sync_subclass_index(Name, OldSuperclass, undefined),
        ok
    catch
        error:badarg -> ok
    end,
    %% BT-4064: a removed class must not keep resolving through the cache.
    beamtalk_class_derived_cache:invalidate().

