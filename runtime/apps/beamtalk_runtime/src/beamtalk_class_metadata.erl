-moduledoc """
ETS table owner for the unified `beamtalk_class_metadata` table.

Holds the class-lifetime metadata that used to live in three separate
class-keyed ETS tables (`beamtalk_class_module`, `beamtalk_class_methods`,
`beamtalk_class_hierarchy`). They were consolidated because they
shared a key (`ClassName`), a concurrency profile (`set` +
`{read_concurrency, true}`), a single writer (the class gen_server), and the
same three lifecycle points (`init`, `update_class`, `terminate`) — and the
`Module` field was duplicated across two of them.

## Row shape

Each row is a `#class_metadata{}` record keyed by `name`:

* `module`      — defining BEAM module, or `undefined` if unset
* `selectors`   — local class-method selectors, or `undefined` if unset
* `superclass`  — superclass atom, `none` for a root class, or `undefined` if unset
* `is_abstract` — whether the class is abstract, or `undefined` if unset
  (ADR 0109 amendment)

`undefined` is the "field never written" sentinel and is distinct from `none`
(an explicitly root class). The typed lookups treat `undefined` as `not_found`,
so a row that carries only one field behaves exactly like the old per-table
absence of the others.

## Table properties

* Type: `set`, `{keypos, #class_metadata.name}` — one row per class name.
* Access: `public`, `named_table` — any process reads; written only by the
  class gen_server via `beamtalk_object_class`.
* `{read_concurrency, true}` — the hierarchy/module/methods reads are on hot
  dispatch and supervisor-init paths.
* Heir: created at app start by `beamtalk_runtime_app:start/2` (the
  long-lived app-master process owns it), then `start/2` calls
  `beamtalk_ets_heir:adopt_owned_tables/0` once the heir is alive so it is set
  as `{heir, ...}`. The table therefore survives both a class-process crash
  and an app-master swap.

## Reverse subclass index

`match_subclasses/1` is answered from a second table,
`beamtalk_class_subclass_index` — a `bag` of `{Superclass, ClassName}` edges,
keyed on `Superclass` — instead of an `ets:match/2` scan of every row in
`?TABLE`. A `bag` table (many rows per key) cannot share `?TABLE`'s `set`
semantics, so this is a genuine second table rather than a field on the
existing row; the "second table" it replaces is only the mental model of a
"seventh, independently-lifecycled table" that the original consolidation weighed against — this
one has no owner module, public API, or lifecycle of its own. It is created
and destroyed by this module's own `new/0`, and every write that can change a
row's `superclass` (`insert/5`, `merge_identity/5`, `delete/1`) maintains it
as an internal side effect via `sync_subclass_index/3`, keyed off the row's
*previous* superclass value (read via `field/2` before the write lands) so a
re-register that changes superclass removes the stale edge from the old
parent rather than leaving it to accumulate. Storing the edge independently of
the superclass's own row (rather than as a `subclasses` list field on it)
means a class's children stay discoverable even if the parent's own row is
gone (e.g. a crash mid-teardown) — matching the exact-scan semantics this
replaces, which never depended on the queried class having a row at all.

## Concurrency

`new/0` uses try/catch around `ets:new/2` for the TOCTOU race between
`ets:info/1` and `ets:new/2`. All read/write ops guard against `badarg` from
a table deleted between an existence check and the op (teardown/shutdown).
""".

