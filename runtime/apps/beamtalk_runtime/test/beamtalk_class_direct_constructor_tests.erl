-module(beamtalk_class_direct_constructor_tests).

%%% **DDD Context:** Object System Context

-moduledoc """
EUnit tests for direct construction on dynamic `new` / `new:` sends.

`beamtalk_class_dispatch:class_send/3` consults the class's baked
`direct_constructors` (generated by Rust's `direct_constructors`, cached in
the unified metadata row) and calls `Module:new()` / `Module:new(Map)` in
the caller for listed selectors; everything else takes the gen_server path.
Keyword constructors are ordinary class methods: the in-caller path of ADR
0142 runs them (BT-4300), and a static send is the guarded direct call
(BT-4301).
""".

-include_lib("eunit/include/eunit.hrl").
-include("beamtalk.hrl").

%% Logger handler callback for the BT-4126 stale-verdict warning tests.
-export([log/2]).

log(LogEvent, #{config := #{parent := Parent}}) ->
    Parent ! {log_event, LogEvent},
    ok.

-define(HELPER, beamtalk_class_direct_ctor_helper).
%% No `new/0` / `new/1` exports: the "missing export falls through" module.
-define(PLAIN_HELPER, beamtalk_class_dispatch_test_helper).

setup() ->
    {ok, _} = application:ensure_all_started(beamtalk_runtime),
    ok = beamtalk_stdlib:init(),
    ok.

start_class(Name, Meta) ->
    start_class_with_module(Name, ?HELPER, Meta).

start_class_with_module(Name, Module, Meta) ->
    start_class_with_module(Name, Module, none, Meta).

start_class_with_module(Name, Module, Superclass, Meta) ->
    %% `function_exported/3` only inspects loaded code: a class whose module
    %% nobody has touched yet fails the export check and takes one gen_server
    %% fallback (which loads it) before going direct. Production classes hit
    %% that fallback naturally; the tests preload so the FIRST send is direct.
    {module, Module} = code:ensure_loaded(Module),
    ClassInfo = #{
        superclass => Superclass,
        module => Module,
        class_methods => #{},
        class_state => #{},
        meta => Meta
    },
    {ok, Pid} = beamtalk_object_class:start_link(Name, ClassInfo),
    unlink(Pid),
    Pid.

stop_class(Pid) ->
    try
        gen_server:stop(Pid, normal, 5000)
    catch
        _:_ -> ok
    end,
    ok.

