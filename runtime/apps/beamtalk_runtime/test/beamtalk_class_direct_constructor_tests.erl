        {"concurrent builders all construct correctly", fun() ->
            %% The fast path touches no shared process: 64 builders × 100
            %% iterations of `new` / `new:` must all build in their own
            %% process (the helper answers the builder pid). Pre-change this
            %% serialized on the class gen_server; now nothing is shared.
            Pid = start_class('BT4099Conc', #{direct_constructors => [new, 'new:']}),
            try
                Parent = self(),
                Worker = fun(N) ->
                    Rs = lists:map(
                        fun(_) ->
                            {
                                beamtalk_class_dispatch:class_send(Pid, new, []),
                                beamtalk_class_dispatch:class_send(Pid, 'new:', [#{n => N}])
                            }
                        end,
                        lists:seq(1, 100)
                    ),
                    Parent ! {done, self(), N, Rs}
                end,
                Workers = [spawn(fun() -> Worker(N) end) || N <- lists:seq(1, 64)],
                Results = [
                    receive
                        {done, W, N, Rs} -> {W, N, Rs}
                    end
                 || W <- Workers
                ],
                ?assertEqual(64, length(Results)),
                lists:foreach(
                    fun({W, N, Rs}) ->
                        ?assertEqual(100, length(Rs)),
                        lists:foreach(
                            fun({Built, {Built1, Map}}) ->
                                ?assertEqual(W, Built),
                                ?assertEqual(W, Built1),
                                ?assertEqual(#{n => N}, Map)
                            end,
                            Rs
                        )
                    end,
                    Results
                )
            after
                stop_class(Pid)
            end
        end}
    ]}.

