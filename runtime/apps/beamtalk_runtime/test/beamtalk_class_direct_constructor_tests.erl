-module(beamtalk_class_direct_constructor_tests).

%%% **DDD Context:** Object System Context

-moduledoc """
EUnit tests for direct construction on dynamic `new` / `new:` sends (BT-4099).

`beamtalk_class_dispatch:class_send/3` consults the class's baked
`direct_constructors` (generated by Rust's `direct_constructors`, cached in
the unified metadata row) and calls `Module:new()` / `Module:new(Map)` in
the caller for listed selectors; everything else takes the gen_server path.
Keyword constructors ride the BT-3639 `direct_class_methods` path unchanged.
""".

-include_lib("eunit/include/eunit.hrl").

-define(HELPER, beamtalk_class_direct_ctor_helper).
%% No `new/0` / `new/1` exports: the "missing export falls through" module.
-define(PLAIN_HELPER, beamtalk_class_dispatch_test_helper).

setup() ->
    {ok, _} = application:ensure_all_started(beamtalk_runtime),
    ok = beamtalk_stdlib:init(),
    ok.

start_class(Name, Meta) ->
    start_class_with_module(Name, ?HELPER, Meta).

start_class_with_module(Name, Module, Meta) ->
    %% `function_exported/3` only inspects loaded code: a class whose module
    %% nobody has touched yet fails the export check and takes one gen_server
    %% fallback (which loads it) before going direct. Production classes hit
    %% that fallback naturally; the tests preload so the FIRST send is direct.
    {module, Module} = code:ensure_loaded(Module),
    ClassInfo = #{
        superclass => none,
        module => Module,
        class_methods => #{},
        class_state => #{},
        meta => Meta
    },
    {ok, Pid} = beamtalk_object_class:start_link(Name, ClassInfo),
    unlink(Pid),
    Pid.

stop_class(Pid) ->
    catch gen_server:stop(Pid, normal, 5000),
    ok.

direct_constructor_test_() ->
    {setup, fun setup/0, fun(_) -> ok end, [
        {"eligible new builds in the caller's process", fun() ->
            Pid = start_class('BT4099DirectNew', #{direct_constructors => [new]}),
            try
                ?assertEqual(self(), beamtalk_class_dispatch:class_send(Pid, new, []))
            after
                stop_class(Pid)
            end
        end},
        {"eligible new: with a map builds in the caller's process", fun() ->
            Pid = start_class('BT4099DirectNew1', #{direct_constructors => ['new:']}),
            try
                ?assertEqual(
                    {self(), #{a => 1}},
                    beamtalk_class_dispatch:class_send(Pid, 'new:', [#{a => 1}])
                )
            after
                stop_class(Pid)
            end
        end},
        {"new absent from the verdict goes through the class gen_server", fun() ->
            Pid = start_class('BT4099Gated', #{direct_constructors => ['new:']}),
            try
                ?assertEqual(Pid, beamtalk_class_dispatch:class_send(Pid, new, []))
            after
                stop_class(Pid)
            end
        end},
        {"meta without the key never constructs directly", fun() ->
            Pid = start_class('BT4099NoKey', #{}),
            try
                ?assertEqual(Pid, beamtalk_class_dispatch:class_send(Pid, new, [])),
                ?assertEqual(
                    {Pid, #{a => 1}},
                    beamtalk_class_dispatch:class_send(Pid, 'new:', [#{a => 1}])
                )
            after
                stop_class(Pid)
            end
        end},
        {"new: with a non-map argument is never eligible", fun() ->
            Pid = start_class('BT4099NonMap', #{direct_constructors => [new, 'new:']}),
            try
                %% The gen_server path owns the legacy fallbacks for this
                %% shape; the direct path must decline before the export check.
                ?assertEqual(
                    error, beamtalk_class_dispatch:lookup_direct_constructor(Pid, 'new:', [1])
                )
            after
                stop_class(Pid)
            end
        end},
        {"missing new/1 export is not called directly", fun() ->
            Pid = start_class_with_module(
                'BT4099NoNew1', ?PLAIN_HELPER, #{direct_constructors => ['new:']}
            ),
            try
                ?assertEqual(
                    error, beamtalk_class_dispatch:lookup_direct_constructor(Pid, 'new:', [#{}])
                )
            after
                stop_class(Pid)
            end
        end},
        {"missing new/0 export is not called directly", fun() ->
            Pid = start_class_with_module(
                'BT4099NoNew0', ?PLAIN_HELPER, #{direct_constructors => [new]}
            ),
            try
                ?assertEqual(
                    error, beamtalk_class_dispatch:lookup_direct_constructor(Pid, new, [])
                )
            after
                stop_class(Pid)
            end
        end},
        {"reload with a changed verdict set updates construction", fun() ->
            Pid = start_class('BT4099Reload', #{direct_constructors => [new]}),
            try
                ?assertEqual(self(), beamtalk_class_dispatch:class_send(Pid, new, [])),
                {ok, _} = beamtalk_object_class:update_class('BT4099Reload', #{
                    module => ?HELPER, meta => #{direct_constructors => []}
                }),
                ?assertEqual(Pid, beamtalk_class_dispatch:class_send(Pid, new, [])),
                {ok, _} = beamtalk_object_class:update_class('BT4099Reload', #{
                    module => ?HELPER, meta => #{direct_constructors => [new]}
                }),
                ?assertEqual(self(), beamtalk_class_dispatch:class_send(Pid, new, []))
            after
                stop_class(Pid)
            end
        end},
        {"runtime class-method funs disable the direct path", fun() ->
            Pid = start_class('BT4099Funs', #{direct_constructors => [new]}),
            try
                beamtalk_class_metadata:set_runtime_class_methods('BT4099Funs', [new]),
                ?assertEqual(
                    error,
                    beamtalk_class_metadata:lookup_direct_constructor('BT4099Funs', new)
                )
            after
                stop_class(Pid)
            end
        end},
        {"eligible keyword ctor builds in the caller's process", fun() ->
            %% BT-4099 bakes keyword ctors into `direct_class_methods`; the
            %% BT-3639 path calls them directly with no runtime change.
            Pid = start_class('BT4099Kw', #{
                direct_class_methods => #{'x:y:' => 'class_x:y:'}
            }),
            try
                ?assertEqual(
                    {self(), 1, 2},
                    beamtalk_class_dispatch:class_send(Pid, 'x:y:', [1, 2])
                )
            after
                stop_class(Pid)
            end
        end},
        {"concurrent builders all construct correctly", fun() ->
            %% The fast path touches no shared process: 64 builders × 100
            %% iterations of `new` / `new:` must all build in their own
            %% process (the helper answers the builder pid). Pre-change this
            %% serialized on the class gen_server; now nothing is shared.
            Pid = start_class('BT4099Conc', #{direct_constructors => [new, 'new:']}),
            try
                Parent = self(),
                Worker = fun(N) ->
                    Rs = lists:map(
                        fun(_) ->
                            {
                                beamtalk_class_dispatch:class_send(Pid, new, []),
                                beamtalk_class_dispatch:class_send(Pid, 'new:', [#{n => N}])
                            }
                        end,
                        lists:seq(1, 100)
                    ),
                    Parent ! {done, self(), N, Rs}
                end,
                Workers = [spawn(fun() -> Worker(N) end) || N <- lists:seq(1, 64)],
                Results = [
                    receive
                        {done, W, N, Rs} -> {W, N, Rs}
                    end
                 || W <- Workers
                ],
                ?assertEqual(64, length(Results)),
                lists:foreach(
                    fun({W, N, Rs}) ->
                        ?assertEqual(100, length(Rs)),
                        lists:foreach(
                            fun({Built, {Built1, Map}}) ->
                                ?assertEqual(W, Built),
                                ?assertEqual(W, Built1),
                                ?assertEqual(#{n => N}, Map)
                            end,
                            Rs
                        )
                    end,
                    Results
                )
            after
                stop_class(Pid)
            end
        end}
    ]}.
