-module(beamtalk_class_direct_constructor_tests).

%%% **DDD Context:** Object System Context

-moduledoc """
EUnit tests for direct construction on dynamic `new` / `new:` sends.

`beamtalk_class_dispatch:class_send/3` consults the class's baked
`direct_constructors` (generated by Rust's `direct_constructors`, cached in
the unified metadata row) and calls `Module:new()` / `Module:new(Map)` in
the caller for listed selectors; everything else takes the gen_server path.
Keyword constructors are ordinary class methods: the in-caller path of ADR
0142 runs them (BT-4300), and a static send is the guarded direct call
(BT-4301).
""".

-include_lib("eunit/include/eunit.hrl").

%% Logger handler callback for the BT-4126 stale-verdict warning tests.
-export([log/2]).

log(LogEvent, #{config := #{parent := Parent}}) ->
    Parent ! {log_event, LogEvent},
    ok.

-define(HELPER, beamtalk_class_direct_ctor_helper).
%% No `new/0` / `new/1` exports: the "missing export falls through" module.
-define(PLAIN_HELPER, beamtalk_class_dispatch_test_helper).

setup() ->
    {ok, _} = application:ensure_all_started(beamtalk_runtime),
    ok = beamtalk_stdlib:init(),
    ok.

start_class(Name, Meta) ->
    start_class_with_module(Name, ?HELPER, Meta).

start_class_with_module(Name, Module, Meta) ->
    start_class_with_module(Name, Module, none, Meta).

start_class_with_module(Name, Module, Superclass, Meta) ->
    %% `function_exported/3` only inspects loaded code: a class whose module
    %% nobody has touched yet fails the export check and takes one gen_server
    %% fallback (which loads it) before going direct. Production classes hit
    %% that fallback naturally; the tests preload so the FIRST send is direct.
    {module, Module} = code:ensure_loaded(Module),
    ClassInfo = #{
        superclass => Superclass,
        module => Module,
        class_methods => #{},
        class_state => #{},
        meta => Meta
    },
    {ok, Pid} = beamtalk_object_class:start_link(Name, ClassInfo),
    unlink(Pid),
    Pid.

stop_class(Pid) ->
    catch gen_server:stop(Pid, normal, 5000),
    ok.

direct_constructor_test_() ->
    {setup, fun setup/0, fun(_) -> ok end, [
        {"eligible new builds in the caller's process", fun() ->
            Pid = start_class('BT4099DirectNew', #{direct_constructors => [new]}),
            try
                ?assertEqual(self(), beamtalk_class_dispatch:class_send(Pid, new, []))
            after
                stop_class(Pid)
            end
        end},
        {"eligible new: with a map builds in the caller's process", fun() ->
            Pid = start_class('BT4099DirectNew1', #{direct_constructors => ['new:']}),
            try
                ?assertEqual(
                    {self(), #{a => 1}},
                    beamtalk_class_dispatch:class_send(Pid, 'new:', [#{a => 1}])
                )
            after
                stop_class(Pid)
            end
        end},
        {"new absent from the verdict goes through the class gen_server", fun() ->
            Pid = start_class('BT4099Gated', #{direct_constructors => ['new:']}),
            try
                ?assertEqual(Pid, beamtalk_class_dispatch:class_send(Pid, new, []))
            after
                stop_class(Pid)
            end
        end},
        {"meta without the key never constructs directly", fun() ->
            Pid = start_class('BT4099NoKey', #{}),
            try
                ?assertEqual(Pid, beamtalk_class_dispatch:class_send(Pid, new, [])),
                ?assertEqual(
                    {Pid, #{a => 1}},
                    beamtalk_class_dispatch:class_send(Pid, 'new:', [#{a => 1}])
                )
            after
                stop_class(Pid)
            end
        end},
        {"new: with a non-map argument is never eligible", fun() ->
            Pid = start_class('BT4099NonMap', #{direct_constructors => [new, 'new:']}),
            try
                %% The gen_server path owns the legacy fallbacks for this
                %% shape; the direct path must decline before the export check.
                ?assertEqual(
                    error, beamtalk_class_dispatch:lookup_direct_constructor(Pid, 'new:', [1])
                )
            after
                stop_class(Pid)
            end
        end},
        {"missing new/1 export is not called directly", fun() ->
            Pid = start_class_with_module(
                'BT4099NoNew1', ?PLAIN_HELPER, #{direct_constructors => ['new:']}
            ),
            try
                ?assertEqual(
                    error, beamtalk_class_dispatch:lookup_direct_constructor(Pid, 'new:', [#{}])
                )
            after
                stop_class(Pid)
            end
        end},
        {"missing new/0 export is not called directly", fun() ->
            Pid = start_class_with_module(
                'BT4099NoNew0', ?PLAIN_HELPER, #{direct_constructors => [new]}
            ),
            try
                ?assertEqual(
                    error, beamtalk_class_dispatch:lookup_direct_constructor(Pid, new, [])
                )
            after
                stop_class(Pid)
            end
        end},
        {"reload with a changed verdict set updates construction", fun() ->
            Pid = start_class('BT4099Reload', #{direct_constructors => [new]}),
            try
                ?assertEqual(self(), beamtalk_class_dispatch:class_send(Pid, new, [])),
                {ok, _} = beamtalk_object_class:update_class('BT4099Reload', #{
                    module => ?HELPER, meta => #{direct_constructors => []}
                }),
                ?assertEqual(Pid, beamtalk_class_dispatch:class_send(Pid, new, [])),
                {ok, _} = beamtalk_object_class:update_class('BT4099Reload', #{
                    module => ?HELPER, meta => #{direct_constructors => [new]}
                }),
                ?assertEqual(self(), beamtalk_class_dispatch:class_send(Pid, new, []))
            after
                stop_class(Pid)
            end
        end},
        {"runtime class-method funs disable the direct path", fun() ->
            Pid = start_class('BT4099Funs', #{direct_constructors => [new]}),
            try
                beamtalk_class_metadata:set_runtime_class_methods('BT4099Funs', [new]),
                ?assertEqual(
                    error,
                    beamtalk_class_metadata:lookup_direct_constructor('BT4099Funs', new)
                )
            after
                stop_class(Pid)
            end
        end},
        {"eligible keyword ctor builds in the caller's process", fun() ->
            %% A keyword ctor is a class method of a stateless class, so the
            %% in-caller path runs it (ADR 0142, BT-4300).
            Pid = start_class('BT4099Kw', #{
                class_method_info => #{'x:y:' => #{arity => 2}},
                process_bound_class_selectors => [new, 'new:']
            }),
            try
                ?assertEqual(
                    {self(), 1, 2},
                    beamtalk_class_dispatch:class_send(Pid, 'x:y:', [1, 2])
                )
            after
                stop_class(Pid)
            end
        end},
        {"concurrent builders all construct correctly", fun() ->
            %% The fast path touches no shared process: 64 builders × 100
            %% iterations of `new` / `new:` must all build in their own
            %% process (the helper answers the builder pid). Pre-change this
            %% serialized on the class gen_server; now nothing is shared.
            Pid = start_class('BT4099Conc', #{direct_constructors => [new, 'new:']}),
            try
                Parent = self(),
                Worker = fun(N) ->
                    Rs = lists:map(
                        fun(_) ->
                            {
                                beamtalk_class_dispatch:class_send(Pid, new, []),
                                beamtalk_class_dispatch:class_send(Pid, 'new:', [#{n => N}])
                            }
                        end,
                        lists:seq(1, 100)
                    ),
                    Parent ! {done, self(), N, Rs}
                end,
                Workers = [spawn(fun() -> Worker(N) end) || N <- lists:seq(1, 64)],
                Results = [
                    receive
                        {done, W, N, Rs} -> {W, N, Rs}
                    end
                 || W <- Workers
                ],
                ?assertEqual(64, length(Results)),
                lists:foreach(
                    fun({W, N, Rs}) ->
                        ?assertEqual(100, length(Rs)),
                        lists:foreach(
                            fun({Built, {Built1, Map}}) ->
                                ?assertEqual(W, Built),
                                ?assertEqual(W, Built1),
                                ?assertEqual(#{n => N}, Map)
                            end,
                            Rs
                        )
                    end,
                    Results
                )
            after
                stop_class(Pid)
            end
        end}
    ]}.

%%====================================================================
%% BT-4126: reload-time warning for stale baked verdicts
%%====================================================================

start_subclass(Name, Superclass, Meta) ->
    start_class_with_module(Name, ?HELPER, Superclass, Meta).

reload(Name, Meta) ->
    {ok, _} = beamtalk_object_class:update_class(Name, #{module => ?HELPER, meta => Meta}),
    ok.

%% Run Fun with a logger handler forwarding every event to this process, and
%% return the BT-4126 warnings (the metadata maps carrying `Key`) it logged.
%% Lifts the primary level to `all` for the run and restores whatever it was
%% (test/sys.config sets `warning` so the warnings_file sink captures them).
stale_warnings(Key, Fun) ->
    HandlerId = bt_4126_stale_verdict_test_handler,
    #{level := OldLevel} = logger:get_primary_config(),
    ok = logger:set_primary_config(level, all),
    ok = logger:add_handler(HandlerId, ?MODULE, #{config => #{parent => self()}, level => all}),
    try
        Fun()
    after
        logger:remove_handler(HandlerId),
        logger:set_primary_config(level, OldLevel)
    end,
    drain_warnings(Key, []).

drain_warnings(Key, Acc) ->
    receive
        {log_event, #{level := warning, meta := #{Key := _} = Meta}} ->
            drain_warnings(Key, [Meta | Acc]);
        {log_event, _} ->
            drain_warnings(Key, Acc)
    after 0 ->
        lists:reverse(Acc)
    end.

%% A class-side `new:` as `class_method_info` carries it for a compiled class.
-define(USER_NEW1, #{'new:' => #{arity => 1}}).

stale_verdict_warning_test_() ->
    {setup, fun setup/0, fun(_) -> ok end, [
        {"reload gaining new: warns naming every transitive stale subclass", fun() ->
            Parent = start_class('BT4126Parent', #{class_method_info => #{}}),
            Child = start_subclass('BT4126Child', 'BT4126Parent', #{
                direct_constructors => [new, 'new:']
            }),
            %% Only `new` baked: `new/0` is its own override slot, never stale.
            NewOnly = start_subclass('BT4126NewOnly', 'BT4126Parent', #{
                direct_constructors => [new]
            }),
            Grandchild = start_subclass('BT4126Grandchild', 'BT4126Child', #{
                direct_constructors => ['new:']
            }),
            try
                Warnings = stale_warnings(stale_direct_constructors, fun() ->
                    reload('BT4126Parent', #{class_method_info => ?USER_NEW1})
                end),
                ?assertMatch(
                    [#{class := 'BT4126Parent', stale_direct_constructors := _}], Warnings
                ),
                [#{stale_direct_constructors := Stale}] = Warnings,
                ?assertEqual(['BT4126Child', 'BT4126Grandchild'], lists:sort(Stale))
            after
                [stop_class(P) || P <- [Grandchild, NewOnly, Child, Parent]]
            end
        end},
        {"reload without a new: change stays silent", fun() ->
            Parent = start_class('BT4126Quiet', #{class_method_info => #{}}),
            Child = start_subclass('BT4126QuietChild', 'BT4126Quiet', #{
                direct_constructors => ['new:']
            }),
            try
                ?assertEqual(
                    [],
                    stale_warnings(stale_direct_constructors, fun() ->
                        reload('BT4126Quiet', #{
                            class_method_info => #{'x' => #{arity => 0}}
                        })
                    end)
                )
            after
                [stop_class(P) || P <- [Child, Parent]]
            end
        end},
        {"reload keeping an existing new: stays silent", fun() ->
            %% Already had `new:`: any stale child was reported when it was
            %% gained, so reloading again must not repeat the warning.
            Parent = start_class('BT4126Kept', #{class_method_info => ?USER_NEW1}),
            Child = start_subclass('BT4126KeptChild', 'BT4126Kept', #{
                direct_constructors => ['new:']
            }),
            try
                ?assertEqual(
                    [],
                    stale_warnings(stale_direct_constructors, fun() ->
                        reload('BT4126Kept', #{class_method_info => ?USER_NEW1})
                    end)
                )
            after
                [stop_class(P) || P <- [Child, Parent]]
            end
        end},
        {"reload gaining new: with no stale subclass stays silent", fun() ->
            Parent = start_class('BT4126Fresh', #{class_method_info => #{}}),
            %% Recompiled against the new parent: verdict already omits `new:`.
            Child = start_subclass('BT4126FreshChild', 'BT4126Fresh', #{
                direct_constructors => [new]
            }),
            try
                ?assertEqual(
                    [],
                    stale_warnings(stale_direct_constructors, fun() ->
                        reload('BT4126Fresh', #{class_method_info => ?USER_NEW1})
                    end)
                )
            after
                [stop_class(P) || P <- [Child, Parent]]
            end
        end},
        {"put_class_method installing new: warns naming the stale subclass", fun() ->
            Parent = start_class('BT4126PutParent', #{class_method_info => #{}}),
            Child = start_subclass('BT4126PutChild', 'BT4126PutParent', #{
                direct_constructors => ['new:']
            }),
            try
                Warnings = stale_warnings(stale_direct_constructors, fun() ->
                    ok = beamtalk_object_class:put_class_method(
                        Parent, 'new:', fun(_Self, Args) -> Args end
                    )
                end),
                ?assertMatch(
                    [
                        #{
                            class := 'BT4126PutParent',
                            stale_direct_constructors := ['BT4126PutChild']
                        }
                    ],
                    Warnings
                ),
                %% Patching it again is not a gain: no repeat.
                ?assertEqual(
                    [],
                    stale_warnings(stale_direct_constructors, fun() ->
                        ok = beamtalk_object_class:put_class_method(
                            Parent, 'new:', fun(_Self, Args) -> Args end
                        )
                    end)
                )
            after
                [stop_class(P) || P <- [Child, Parent]]
            end
        end},
        {"class-method changes leave no stale static verdict to warn about", fun() ->
            %% BT-4301: every static class-method call site is guarded by
            %% `direct_call_ok/2` (ADR 0142 §2), which a runtime fun turns
            %% off, so nothing is baked that a reload or `put_class_method`
            %% could strand: the BT-4126 class-method warning is gone.
            Info = #{'x:y:' => #{arity => 2}, 'make' => #{arity => 0}},
            Pid = start_class('BT4301NoStale', #{class_method_info => Info}),
            try
                ?assertEqual(
                    [],
                    stale_warnings(stale_direct_class_methods, fun() ->
                        reload('BT4301NoStale', #{class_method_info => #{}}),
                        ok = beamtalk_object_class:put_class_method(
                            Pid, 'make', fun(_Self) -> made end
                        )
                    end)
                ),
                ?assertNot(
                    beamtalk_class_shadow_flags:direct_call_ok(
                        beamtalk_class_registry:class_object_tag('BT4301NoStale'),
                        'BT4301NoStale'
                    )
                )
            after
                stop_class(Pid)
            end
        end}
    ]}.
