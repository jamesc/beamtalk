"""Generate the ADR 0137 actor-field-closure matrix (BT-4009).

Writes the fixture actor and the BUnit test that runs every cell on a BEAM:

    block shape x send kind x position   (at home)
    block shape x send kind              (away: the block runs in another process)

Each cell is one method on the fixture actor and one test. The expected value
and the final field value come from the small model below, not from the
compiler, so a cell fails when the compiler's answer differs from what the
language says. Re-run after changing the matrix:

    python3 scripts/gen-actor-closure-matrix.py

Outputs (checked in):
    stdlib/test/fixtures/closure_matrix_subject.bt
    stdlib/test/actor_closure_matrix_test.bt
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "stdlib/test/fixtures/closure_matrix_subject.bt"
TEST = ROOT / "stdlib/test/actor_closure_matrix_test.bt"

HEADER = """// Copyright 2026 James Casey
// SPDX-License-Identifier: Apache-2.0

// GENERATED by scripts/gen-actor-closure-matrix.py -- do not edit.
// ADR 0137 Phase 2b (BT-4009): the actor-field-closure matrix.
"""

N0 = 2  # initial value of the `n` field
BASE = 10  # a read-only captured local, `base`

# --- block shapes: (source, model) -------------------------------------------------
# The model takes the state {n} and returns the block's value, mutating the state.


def m_r(s):
    return s["n"]


def m_rw(s):
    s["n"] += 1
    return s["n"]


def m_rwb(s):
    s["n"] += BASE
    return s["n"]


def m_rb(s):
    return s["n"] + BASE


def m_ss(s):
    s["n"] += s["n"]
    return s["n"]


SHAPES = {
    "R": ("self.n", m_r),
    "RW": ("self.n := self.n + 1. self.n", m_rw),
    "S": ("self bump. self.n", m_rw),
    "RWB": ("self.n := self.n + base. self.n", m_rwb),
    "RB": ("self.n + base", m_rb),
    "SS": ("self.n := self.n + self peek. self.n", m_ss),
}

# --- send kinds ------------------------------------------------------------------
# name -> (prelude lines, expression with BODY, kind, runs, result)
#   kind "stmt": the send yields nothing used; kind "value": yields the last body value;
#   kind "list": yields the list of body values.
# `params` is the block header; the body is spliced where BODY appears.

SENDS = {
    "litValue": (["[BODY] value"], "value", 1),
    "varValue": (["b := [BODY]", "b value"], "value", 1),
    "twice": (["self twice: [BODY]"], "stmt", 2),
    "doList": (["#(1, 2, 3) do: [:e | BODY]"], "stmt", 3),
    "timesRepeat": (["3 timesRepeat: [BODY]"], "stmt", 3),
    "toDo": (["1 to: 3 do: [:e | BODY]"], "stmt", 3),
    "whileLoop": (["i := 0", "[i < 3] whileTrue: [BODY. i := i + 1]"], "stmt", 3),
    "collect": (["#(1, 2, 3) collect: [:e | BODY]"], "list", 3),
    "inject": (["#(1, 2, 3) inject: 0 into: [:a :e | BODY]"], "value", 3),
    "ifTrue": (["self.n >= 0 ifTrue: [BODY] ifFalse: [0]"], "value", 1),
    "onDo": (["[BODY] on: Error do: [:x | -1]"], "value", 1),
    "ensure": (["[BODY] ensure: [self.n]"], "value", 1),
    "stored": (["self.f := [BODY]", "self.f value"], "value", 1),
    "nested": (["#(1, 2) do: [:e | #(1, 2) do: [:g | BODY]]"], "stmt", 4),
    "inCond": (["self.n >= 0 ifTrue: [#(1, 2) do: [:e | BODY]]"], "stmt", 2),
    "onDoInDo": (["#(1, 2) do: [:e | [BODY] on: Error do: [:x | nil]]"], "stmt", 2),
    # a block handed on to another method of the actor, which runs it
    "passDo": (["self runAll: [:e | BODY]"], "stmt", 3),
    # `^` inside the block: the method answers `self.n` as of the return
    "nlrDo": (["#(1, 2, 3) do: [:e | BODY. e == 2 ifTrue: [^ self.n]]"], "nlr", 2),
    "nlrOnDo": (["[BODY. ^ self.n] on: Error do: [:x | -1]"], "nlr", 1),
    "nlrEnsure": (["[BODY. ^ self.n] ensure: [self.n]"], "nlr", 1),
    "nlrWhile": (
        ["i := 0", "[i < 3] whileTrue: [BODY. i := i + 1. i == 2 ifTrue: [^ self.n]]"],
        "nlr",
        2,
    ),
}

FINISH = "(self.n * 100)"
SUM = "(r inject: 0 into: [:s :x | s + x])"


def run_send(send, shape):
    """Run the model: returns (yielded value, state)."""
    _, kind, runs = SENDS[send]
    state = {"n": N0}
    model = SHAPES[shape][1]
    values = [model(state) for _ in range(runs)]
    if kind == "list":
        return values, state
    if kind == "value":
        return values[-1], state
    return None, state  # "stmt" and "nlr" yield nothing; an `nlr` method answers `self.n`


def literal(value):
    if isinstance(value, list):
        return "#(" + ", ".join(str(v) for v in value) + ")"
    return str(value)


def home_cells():
    cells = []
    for shape, (body_src, _) in SHAPES.items():
        for send, (lines, kind, _) in SENDS.items():
            body = body_src
            rendered = [line.replace("BODY", body) for line in lines]
            pre, expr = rendered[:-1], rendered[-1]
            value, state = run_send(send, shape)
            positions = ["stmt"] if kind == "stmt" else ["stmt", "assign", "return"]
            if kind == "nlr":
                positions = ["early"]
            # The validator still rejects an inlined `[...] value` that writes a field
            # or sends to `self` as a message argument (BT-3981, until BT-3947).
            if kind == "value" and not (send == "litValue" and shape not in ("R", "RB")):
                positions.append("operand")
            for position in positions:
                name = f"{send}{shape}{position.capitalize()}"
                code = ([f"base := {BASE}"] if "base" in body else []) + pre
                n = state["n"]
                finish = n * 100
                if position == "stmt":
                    code += [expr, FINISH]
                    expected = finish
                elif position == "assign":
                    code += [f"r := {expr}"]
                    if kind == "list":
                        code += [f"{SUM} * 10000 + {FINISH}"]
                        expected = sum(value) * 10000 + finish
                    else:
                        code += [f"r * 10000 + {FINISH}"]
                        expected = value * 10000 + finish
                elif position == "operand":
                    code += [f"r := 1 + ({expr})", f"r * 10000 + {FINISH}"]
                    expected = (1 + value) * 10000 + finish
                elif position == "early":
                    code += [expr, "0"]
                    expected = n
                else:  # return
                    code += [expr]
                    expected = value
                cells.append((name, code, expected, n))
    return cells


# --- away cells: the block runs in another process --------------------------------
AWAY_SENDS = {
    "run": ("other run: b", "value"),
    "collectRun": ("other collect: #(1, 2, 3) run: [:e | b value]", "list"),
    "viaField": ("self.f := b. other run: self.f", "value"),
}
AWAY_SHAPES = ["R", "RW"]


def away_cells():
    cells = []
    for shape in AWAY_SHAPES:
        body = SHAPES[shape][0]
        for send, (expr, kind) in AWAY_SENDS.items():
            name = f"away{send[0].upper()}{send[1:]}{shape}"
            # `b` captures the state at its creation; the field is changed after.
            code = [f"b := [{body}]", "self.n := 50", expr]
            if shape == "R":
                # a read away sees the state captured when the block was created
                expected = literal([N0, N0, N0]) if kind == "list" else str(N0)
                cells.append((name, code, expected, 50, None))
            else:
                # a write away raises
                # the failed call leaves the actor as it was before it
                cells.append((name, code, None, N0, "actor_state_unreachable"))
    return cells


def method_source(name, code):
    lines = [f"  {name} =>"]
    lines += [f"    {line}" for line in code]
    return "\n".join(lines)


def main():
    home = home_cells()
    away = away_cells()

    fixture = [HEADER]
    fixture.append("Actor subclass: ClosureMatrixSubject")
    fixture.append(f"  state: n = {N0}")
    fixture.append("  state: f = nil")
    fixture.append("")
    fixture.append("  n => self.n")
    fixture.append("  peek => self.n")
    fixture.append("  bump => self.n := self.n + 1")
    fixture.append("")
    fixture.append("  runAll: aBlock => #(1, 2, 3) do: [:e | aBlock value: e]")
    fixture.append("")
    fixture.append("  twice: aBlock =>")
    fixture.append("    aBlock value")
    fixture.append("    aBlock value")
    for name, code, _, _ in home:
        fixture.append("")
        fixture.append(method_source(name, code))
    for name, code, _, _, _ in away:
        fixture.append("")
        # away methods take the runner as a parameter
        fixture.append(method_source(f"{name}: other", code))
    FIXTURE.write_text("\n".join(fixture) + "\n")

    test = [HEADER]
    test.append("TestCase subclass: ActorClosureMatrixTest")
    for name, _, expected, n in home:
        test.append("")
        test.append(f"  test{name[0].upper()}{name[1:]} =>")
        test.append("    c := ClosureMatrixSubject spawn")
        test.append(f"    self assert: c {name} equals: {literal(expected)}")
        test.append(f"    self assert: c n equals: {n}")
    for name, _, expected, n, error in away:
        test.append("")
        test.append(f"  test{name[0].upper()}{name[1:]} =>")
        test.append("    c := ClosureMatrixSubject spawn")
        test.append("    runner := ClosureCellRunner spawn")
        if error is None:
            test.append(f"    self assert: (c {name}: runner) equals: {expected}")
        else:
            test.append(f"    self should: [c {name}: runner] raise: #{error}")
        test.append(f"    self assert: c n equals: {n}")
    TEST.write_text("\n".join(test) + "\n")
    print(f"{len(home)} home cells, {len(away)} away cells")


main()
