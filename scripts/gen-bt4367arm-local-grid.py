"""Generate the BT-4367 arm-local differential grid fixtures.

Every shape is written twice, at the method root (`...Root`) and inside the arm
of a conditional that writes no outer local (`...Arm:`). The grid is

    conditional selector x position of the conditional x body shape

and it is emitted for two class kinds, which differ only in the class header
and the field declaration (`Actor` + `state:` versus `Value` + `field:`).
`bt4367arm_local_grid_test.bt` asserts the two answer the same. Re-run after
changing the grid:

    python3 scripts/gen-bt4367arm-local-grid.py

Outputs (checked in):
    stdlib/test/fixtures/bt4367arm_local_grid_{actor,value}.bt
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "stdlib/test/fixtures"

HEADER = """\
// Copyright 2026 James Casey
// SPDX-License-Identifier: Apache-2.0

// BT-4367: differential fixture ({kind} method). Every shape is written twice: at
// the method root (`...Root`, the proven producer path) and inside the arm of a
// conditional that writes no outer local (`...Arm:`, a plain `BranchArm` frame,
// BT-3911), where a loop or fold writes a local of the arm. The two must answer
// the same. The grid is conditional selector (for a two-arm selector, the loop in
// the first arm and, as `...Second`, in the second arm) x position of the
// conditional (last statement, non-last statement, assigned value, `^`, operand)
// x body shape (an assigned `inject:into:`, a `do:` statement, an `inject:into:`
// or `collect:` as the arm's value, an early `^`). A collection as an operand is
// a type error at the root too, so it is left out. Asserted in
// bt4367arm_local_grid_test.bt. Generated by scripts/gen-bt4367arm-local-grid.py;
// do not edit by hand.

{superclass} subclass: Bt4367ArmLocalGrid{cls}
  {decl}: n = 0
"""

KINDS = [
    # file suffix, prose kind, superclass, class suffix, field keyword
    ("actor", "actor", "Actor", "Actor", "state"),
    ("value", "value", "Value", "Value", "field"),
]

INJECT = [
    "#(1, 2)",
    "  inject: 0",
    "  into: [:acc :e |",
    "    m := m + e",
    "    acc + e",
    "  ]",
]


def with_prefix(prefix, lines):
    """Prefix the first line of `lines` (a multi-line expression)."""
    return [prefix + lines[0]] + lines[1:]


# shape -> (statements before the value, the value expression, early return?)
# Line lists at indent 0.
SHAPES = [
    ("assign_inject", ["m := 0"] + with_prefix("s := ", INJECT), ["m + s"], False),
    ("stmt_do", ["m := 0", "#(1, 2) do: [:e | m := m + e]"], ["m"], False),
    ("final_inject", ["m := 0"], INJECT, False),
    ("final_collect", ["m := 0"], ["#(1, 2) collect: [:e | m := m + e]"], False),
    ("early_return", ["m := 0"] + with_prefix("s := ", INJECT), ["m + s"], True),
]

POSITIONS = ["last", "nonlast", "assign", "return", "operand"]

# Group order in the file: (name, branch keywords, index of the branch that holds
# the loop). The other branch of a two-arm selector answers 0.
TWO_ARM = [
    ("ifTrue_ifFalse", ("ifTrue", "ifFalse"), 0),
    ("ifNil_ifNotNil", ("ifNil", "ifNotNil"), 0),
    ("ifNotNil_ifNil", ("ifNotNil", "ifNil"), 0),
    ("ifTrue_ifFalseSecond", ("ifTrue", "ifFalse"), 1),
    ("ifNil_ifNotNilSecond", ("ifNil", "ifNotNil"), 1),
    ("ifNotNil_ifNilSecond", ("ifNotNil", "ifNil"), 1),
]
ONE_ARM = ["ifTrue", "ifFalse", "ifNil", "ifNotNil"]

GROUPS = (
    [TWO_ARM[0]]
    + [(k, (k,), 0) for k in ONE_ARM[:2]]
    + TWO_ARM[1:]
    + [(k, (k,), 0) for k in ONE_ARM[2:]]
)


def indent(lines, n):
    return [(" " * n + l) if l else l for l in lines]


def root_body(shape, pos):
    _, pre, value, early = shape
    name = shape[0]
    if early:
        # An early `^` makes the position irrelevant at the root.
        return pre + with_prefix("^", value)
    if pos == "last":
        return pre + value
    if pos == "nonlast":
        mid = ["@expect discarded_update"] if name == "final_collect" else []
        return pre + mid + value + ["7"]
    if pos == "assign":
        return pre + with_prefix("r := ", value) + ["r"]
    if pos == "return":
        return pre + with_prefix("^", value)
    out = pre + with_prefix("1 + (", value)
    out[-1] += ")"
    return out


def arm_body(shape, pos, branches, body_idx):
    _, pre, value, early = shape
    body = pre + with_prefix("^", value) if early else pre + value
    lines = ["c"]
    for i, kw in enumerate(branches):
        opener = f"  {kw}: [" + (":_x |" if kw == "ifNotNil" else "")
        if i == body_idx or len(branches) == 1:
            lines += [opener] + indent(body, 4) + ["  ]"]
        else:
            other = "[:_x | 0]" if kw == "ifNotNil" else "[0]"
            lines += [f"  {kw}: {other}"]
    if pos == "last":
        return lines
    if pos == "nonlast":
        return lines + ["7"]
    if pos == "assign":
        return ["r := " + lines[0]] + lines[1:] + ["r"]
    if pos == "return":
        return ["^" + lines[0]] + lines[1:]
    lines = ["1 + (" + lines[0]] + lines[1:]
    lines[-1] += ")"
    return lines


def method(header, lines):
    return "\n".join([f"  {header} =>"] + indent(lines, 4)) + "\n"


def render(kind):
    _, prose, sup, cls, decl = kind
    out = [HEADER.format(kind=prose, superclass=sup, cls=cls, decl=decl)]
    for name, branches, body_idx in GROUPS:
        for pos in POSITIONS:
            for shape in SHAPES:
                if pos == "operand" and shape[0] == "final_collect":
                    continue
                stem = f"{name}_{pos}_{shape[0]}"
                out.append(method(f"{stem}Root", root_body(shape, pos)))
                out.append(
                    method(f"{stem}Arm: c", arm_body(shape, pos, branches, body_idx))
                )
    return "\n".join(out)


def main():
    for kind in KINDS:
        path = FIXTURES / f"bt4367arm_local_grid_{kind[0]}.bt"
        path.write_text(render(kind))
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
